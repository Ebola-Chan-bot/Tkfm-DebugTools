'use strict';
/*
 * _验窗节拍重复.js —— 窗对齐构造 vs 节拍对齐构造 候选重合度验证
 * 依据：R9d 记录窗对齐构造 S族 = 节拍族 ∪ 机制周期族；两段各自 TopK3 独立爬山（30000+谷底8 ≈60s/候选）。
 *   若窗段 TopK 里有与节拍段爬过的 toks 完全相同的候选 → 该次爬山结果必然逐位相同（确定性算法、同起点同预算）
 *   → 窗段可对该候选直接复用节拍段结果，数学零行为变化。
 * 输出：每队 节拍TopK toks键 集合、窗TopK toks键 集合、重合数、重合候选的构造dmg。
 */
const 排程 = require('./排程器.js');
const 适配 = require('./引擎适配.js');
const BOND = [5, 5, 5, 5, 5];

// R9g 中 节拍ms>0 且 窗ms>0 的代表队（低分难队 + 常规队混样）
const 队 = [
  ['시엘低分', [10210, 10212, 10196, 10134, 10072]],
  ['후지카', [10213, 10190, 10167, 10164, 10155]],
  ['94队', [10197, 10152, 10096, 10177, 10163]],
  ['승나미', [10177, 10060, 10211, 10208, 10197]],
  ['나리', [10202, 10212, 10133, 10210, 10072]],
  ['얀코相位难', [10197, 10152, 10096, 10193, 10147]],
  ['얀코177', [10197, 10152, 10177, 10163, 10147]],
  ['闸外2', [10197, 10152, 10196, 10163, 10147]],
];

const 键 = t => t.map(x => x.idx + x.act).join('');
const inst = 适配.createEngine();
let 总窗候选 = 0, 总重合 = 0;
for (const [名, ids] of 队) {
  let 节拍候, 窗候;
  try {
    节拍候 = 排程.节拍对齐构造(inst, ids, BOND, { TopK: 3 });
    窗候 = 排程.窗对齐构造(inst, ids, BOND, { TopK: 3 });
  } catch (e) { console.log(`${名}: 构造异常 ${e.message}`); continue; }
  const 节拍键 = new Set(节拍候.map(c => 键(c.toks)));
  const 重合 = 窗候.filter(c => 节拍键.has(键(c.toks)));
  总窗候选 += 窗候.length; 总重合 += 重合.length;
  console.log(`${名}[${ids}]: 节拍TopK=${节拍候.length} 窗TopK=${窗候.length} 重合=${重合.length}` +
    (重合.length ? ' → 窗候选#' + 窗候.map((c, i) => 节拍键.has(键(c.toks)) ? i + 1 : null).filter(x => x != null).join(',') : ''));
  窗候.forEach((c, i) => {
    const dup = 节拍键.has(键(c.toks));
    console.log(`    窗#${i + 1} S={${c.S}} ${c.buff窗 ? '窗憋' : '准点'} dmg=${(c.dmg / 1e9).toFixed(2)}G ${dup ? '【与节拍重复】' : ''}`);
  });
}
console.log(`\n合计: 窗TopK候选=${总窗候选} 与节拍重复=${总重合} (${(总重合 / Math.max(1, 总窗候选) * 100).toFixed(0)}%)`);
console.log('若重复率高 → 窗段对重复候选跳过爬山直接复用节拍段结果（零行为变化，省~60s/重复候选）');
