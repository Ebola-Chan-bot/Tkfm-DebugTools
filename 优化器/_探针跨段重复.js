'use strict';
/*
 * _探针跨段重复.js —— 量化"全局构造去重"的天花板（只构造，不爬山，秒级）
 * 洞见：相位(17.9%)+节拍(16.8%)+窗(44.8%)+序重排 ≈81% 耗时都是同一模式——对某构造 toks 跑一次爬山(30000+谷底8)再 max 取优。
 *   窗段 68% 内部重复、相位两档 100% 重复只是局部症状。本探针统计：
 *   ① 节拍对齐 TopK 内部 toks 重复（若也高 → 第三个零风险局部去重点）
 *   ② 四段所有"送去爬山的构造 toks"的跨段去重后总量 vs 去重前（=全局构造memo表的收益天花板）
 *   ③ 每队去重前爬山次数 vs 去重后 → 直接估全局省比例
 */
const 排 = require('./排程器.js');
const 适配 = require('./引擎适配.js');
const 键 = t => t.map(x => x.idx + x.act).join('');
const inst = 适配.createEngine();
const BOND = [5, 5, 5, 5, 5];

// 取 R9g 里相位/节拍/窗都触发过的难队（终<100 靠兜底救的），它们才吃全部四段
const 队 = [
  ['후지카98.02', [10213, 10190, 10167, 10164, 10155]],
  ['94队', [10197, 10152, 10096, 10177, 10163]],
  ['승나미', [10177, 10060, 10211, 10208, 10197]],
  ['시엘', [10210, 10212, 10196, 10134, 10072]],
  ['나리', [10202, 10212, 10133, 10210, 10072]],
  ['얀코相位难', [10197, 10152, 10096, 10193, 10147]],
  ['얇코177', [10197, 10152, 10177, 10163, 10147]],
  ['闸外2', [10197, 10152, 10196, 10163, 10147]],
];

let 总爬次去重前 = 0, 总爬次去重后 = 0;
for (const [名, ids] of 队) {
  const 起点 = [];   // 收集"送去爬山的构造 toks"，与生产链路各段调用对齐
  const 记 = (arr) => arr.forEach(c => { if (c && c.toks && c.toks.length === 65) 起点.push(c.toks); });

  // 相位兜底：档 5 / 99 各一个构造
  记([{ toks: (排.相位对齐构造(inst, ids, BOND, { 最大憋: 5 }) || {}).toks }]);
  记([{ toks: (排.相位对齐构造(inst, ids, BOND, { 最大憋: 99 }) || {}).toks }]);
  // 节拍：TopK3 数组
  const 节拍 = 排.节拍对齐构造(inst, ids, BOND, { TopK: 3 }) || [];
  记(节拍);
  // 窗对齐：爬山候选（数组模式，未加爬山预算 → 返回最终候选）
  const 窗 = 排.窗对齐构造(inst, ids, BOND, { TopK: 3 }) || [];
  记(窗);

  const 去重前 = 起点.length;
  const 集 = new Set(起点.map(键));
  const 去重后 = 集.size;
  总爬次去重前 += 去重前; 总爬次去重后 += 去重后;
  // 节拍内部重复
  const 节拍distinct = new Set(节拍.filter(c => c && c.toks).map(c => 键(c.toks))).size;
  console.log(`${名}: 四段爬山起点 去重前=${去重前} 去重后=${去重后} 省=${去重前 - 去重后} | 节拍TopK${节拍.length}/distinct${节拍distinct}${节拍distinct < 节拍.length ? '【节拍内部也重复!】' : ''}`);
}
console.log(`\n合计: 爬山调用 去重前=${总爬次去重前} 去重后=${总爬次去重后} 省=${总爬次去重前 - 总爬次去重后} (${((总爬次去重前 - 总爬次去重后) / 总爬次去重前 * 100).toFixed(0)}%)`);
console.log('说明：全局构造memo表(按toks键缓存爬山结果)可一次消除相位档重复+节拍内部重复+窗内部重复+跨段重复；');
console.log('     零行为变化(爬山确定性纯函数+max取优+兜底段只用返回值不读引擎残留)。这是四段局部去重的"泛化终极形态"。');
