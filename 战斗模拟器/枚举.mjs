const 语义名正 = new Map();
const 语义名反 = [];
export function 登记语义名(名称) {
    if (名称 === null || 名称 === undefined) return 0;
    const 已 = 语义名正.get(名称);
    if (已 !== undefined) return 已;
    const 码 = 100000 + 语义名反.length;
    语义名正.set(名称, 码);
    语义名反.push(名称);
    return 码;
}
export const 语义名 = 码 => 语义名反[码 - 100000] ?? String(码);
