function 修复命令引号(文本) {
    return 文本.split('\n').map(行 => {
        const 修复 = 行.replace(/(触发|追加|发动|开启)[」"](?=(?:使|以|受到|被治疗|攻击力|普攻伤害|必杀伤害|必杀技伤害))/g, '$1「').replace(/时1发动/g, '时,发动');
        if (修复 === 行) return 行;
        const 未闭合 = [...修复].reduce((深度, 字) => 深度 + (字 === '「' ? 1 : 字 === '」' ? -1 : 0), 0);
        return 修复 + '」'.repeat(Math.max(0, 未闭合));
    }).join('\n');
}

