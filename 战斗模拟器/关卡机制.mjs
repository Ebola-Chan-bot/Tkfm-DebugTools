// 关卡机制.mjs —— 关卡专属机制入口与通用流程适配。机制本体来自 Skill_C 与 EnemyAI 数据，本模块不保存另一套关卡状态机，也不按中文技能名计算数值。

import { 夏日行动, 夏日机制 } from './关卡数据.mjs';
import { 原包机制 as 原包关卡机制 } from './原包运行时.mjs';

function 含伤害(编号, 路径 = new Set()) {
    const 效果 = 原包关卡机制.技能[编号]?.效果;
    if (!效果 || 路径.has(编号)) return false;
    if (效果.类型 === '伤害') return true;
    const 新路径 = new Set(路径).add(编号);
    return (效果.子技能 || []).some(子编号 => 含伤害(子编号, 新路径));
}

// 钩子接口由引擎构造后传入，含所需助手：添加增益/记录/标记日志归属/我方承伤/敌方承伤/当前攻击/加成/执行敌方技能/按动作批次/派发敌方必杀/结束敌方回合/处于防御/抽取随机目标。

export function 夏日机制结算(状态, 操作, 接口) {
    const 记录 = 夏日机制.find(项 => 项[0] === 操作.技能);
    if (!记录) throw new Error('未知夏日机制');
    const 技能编号 = 记录[1];
    // 夏日机制只按技能ID执行数据；解除娜娜防御没有技能ID，属于通用解除防御动作。
    if (技能编号) 接口.执行原包技能(状态, 状态.首领, 技能编号, { 动作类别: '触发' });
    else 接口.解除敌方防御(状态, 状态.敌人[1]);
    接口.记录(状态, '机制', 操作.技能);
}

export function 夏日敌方行动(状态, 操作, 事件 = false, 批次 = false, 接口) {
    return 接口.按动作批次(状态, () => {
        if (!事件 && 状态.阶段 !== '敌方') throw new Error('我方仍有角色尚未行动');
        const 单位 = 状态.敌人[操作.位置];
        if (!单位 || 单位.生命 <= 0 || (!事件 && 单位.已行动)) throw new Error('该敌人当前无法行动');
        let 技能 = 操作.技能;
        let 技能编号 = 夏日行动[单位.编号]?.find(项 => 项[0] === 技能)?.[1];
        if (!夏日行动[单位.编号]?.some(项 => 项[0] === 技能)) throw new Error('该敌人不能使用此技能');
        // 蓄力技能和解除技都由原包记录关联，中文名称只用于日志展示，不参与数值选择。
        if (单位.蓄力?.原包技能 && 状态.回合 - 单位.蓄力.开始回合 >= (单位.蓄力.持续 || 1)) {
            技能编号 = 单位.蓄力.原包技能;
            单位.蓄力 = null;
        }
        if (!事件) 单位.已行动 = true;
        状态.敌方行动记录.push(`${单位.名称}:${技能}`);
        接口.标记日志归属(状态, '敌方');
        接口.记录(状态, '敌方', `${单位.名称} · ${技能}`);
        if (技能编号) 接口.执行原包技能(状态, 单位, 技能编号, { 动作类别: '触发' });
        if (技能编号 && 含伤害(技能编号)) 接口.派发原包触发(状态, 单位, '攻击', { 动作类别: '触发' });
        if (技能 === '普攻') 接口.派发原包触发(状态, 单位, '普攻', { 动作类别: '普攻' });
        if (!事件 && !批次 && (状态.队伍.every(角色 => 角色.生命 <= 0) || 状态.敌人.every(敌人 => 敌人.生命 <= 0 || 敌人.已行动))) 接口.结束敌方回合(状态, 状态.敌方行动记录.join(' / '));
    });
}
