const 输出技能 = {};
const 展开中 = new Set();
function 展开(编号, 路径列 = []) {
    if (输出技能[编号]) return 输出技能[编号];
    const 项 = 记录.get(编号);
    if (!项) throw new Error(`Skill_C 缺少技能记录：${编号}，路径 ${路径列.join('→')}`);
    if (歧义.has(编号)) throw new Error(`技能 ${编号} 存在不同记录候选：${[...记录.get(编号) ? [记录.get(编号)] : [], ...歧义.get(编号)].map(项 => 项.偏移).join('/')}`);
    if (展开中.has(编号)) return 输出技能[编号];
    展开中.add(编号);
    const 效果 = 翻译记录(项);
    const 结果 = { 编号, 名称: 项.文本?.[0] || `技能${编号}`, 说明: 项.文本?.[1] || '', 偏移: 项.偏移, 位: 项.位, 作用域: 项.作用域, 效果码: 项.效果码, 原始字段: { 阶段码: 项.阶段码, 职业码: 项.职业码, 参数: 项.参数, 原始记录: 项.原始记录 }, 效果 };
    输出技能[编号] = 结果;
    for (const 子编号 of 效果.子技能 || []) 展开(子编号, [...路径列, 编号]);
    展开中.delete(编号);
    return 结果;
}

function 技能组字段(组编号, 槽位) {
    const 数量 = 技能组字节.readUInt32LE(0);
    if (技能组字节.length !== 4 + 数量 * 44) throw new Error('SkillGroup记录边界不正确');
    for (let 序 = 0; 序 < 数量; 序++) {
        const 偏移 = 4 + 序 * 44;
        if (技能组字节.readUInt32LE(偏移) === 组编号) return 技能组字节.readUInt32LE(偏移 + 槽位 * 4);
    }
    throw new Error(`SkillGroup缺少技能组：${组编号}`);
}
