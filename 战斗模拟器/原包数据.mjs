        被动: { 颠倒镜: 原包敌方资料.颠倒镜.敌人[0].被动技能, 爱你至死不渝SP: 原包敌方资料.爱你至死不渝SP.敌人[0].被动技能, 夏日尾声: Object.fromEntries(原包敌方资料.夏日尾声.敌人.map(单位 => [单位.编号, 单位.被动技能.filter(Boolean)])) },
