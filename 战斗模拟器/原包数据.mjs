// 字节读取器：兼容 Node Buffer 与浏览器 Uint8Array（DataView 取底层缓冲，Buffer 池化偏移也正确）；文本仅取名称与人工核对用，数值一律以原始字段为准。
function 造读取器(字节) {
    const 视图 = new DataView(字节.buffer, 字节.byteOffset, 字节.byteLength);
    return { 字节, 长度: 字节.byteLength, 读32: 偏移 => 视图.getUint32(偏移, true), 读16: 偏移 => 视图.getUint16(偏移, true), 读i32: 偏移 => 视图.getInt32(偏移, true) };
}

function 转十六进制(段) {
    let 串 = '';
    for (const 字节 of 段) 串 += 字节.toString(16).padStart(2, '0');
    return 串;
}

