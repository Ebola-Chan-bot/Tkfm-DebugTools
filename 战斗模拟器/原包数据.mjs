        校核: { 颠倒镜记录数: 颠倒镜编号.length, 夏日记录数: 夏日缺.length, SP61锚点: { '26647': { 效果: '伤害', 倍率: 2 }, '26649': { 属性: '造成伤害', 数值: 0.1, 上限: 6 }, '26650': { 属性: '受到伤害', 数值: 0.1, 上限: 6 }, '26658': { 异常: '沉默', 持续: 3 }, '26662': { 异常: '睡眠', 持续: 2, 受伤增加: 1 } }, 未支持, 覆盖 },
