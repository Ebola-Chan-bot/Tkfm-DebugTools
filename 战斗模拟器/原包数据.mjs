// 敌方组推导：关卡编号→Stage_C 编组编号→MonsterGroup 敌人编号序列（原包直读，供解析原包机制 按敌构建校核根）。
export function 敌方组推导(关卡字节, 编组字节, 关卡编号列 = 关卡编号组) {
    const 组 = [];
    for (const 关卡编号 of 关卡编号列) {
        for (let o = 4; o + 60 <= 关卡字节.length; o += 60) {
            if ((关卡字节[o] | (关卡字节[o + 1] << 8)) !== 关卡编号) continue;
            const 编组编号 = 关卡字节[o + 17] | (关卡字节[o + 18] << 8);
            for (let q = 4; q + 22 <= 编组字节.length; q += 22) {
                if ((编组字节[q] | (编组字节[q + 1] << 8)) !== 编组编号) continue;
                for (let i = 0; i < 10; i++) {
                    const 敌 = 编组字节[q + 2 + i * 2] | (编组字节[q + 3 + i * 2] << 8);
                    if (敌 && 组[组.length - 1] !== 敌) 组.push(敌);
                }
                break;
            }
            break;
        }
    }
    return [...new Set(组)];
}
