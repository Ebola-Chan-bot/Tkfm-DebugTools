// 解析原包机制：输入原始字节与文本表，输出与原包关卡机制.json 同构的机制结构；颠倒镜/夏日/SP61 校核门禁内嵌，数据异常时加载即失败而非静默错战。
export function 解析原包机制({ 技能字节, 技能组字节, 文本表 }) {
    const 技能 = 造读取器(技能字节);
    const 技能组 = 造读取器(技能组字节);
    const 文本 = new Map(文本表.filter(项 => 项.分表 === 0).map(项 => [项.编号, 项.文本]));

// Skill_C 含容器引用和变体，不能按固定行切片；真实记录由编号、站位参数和效果码共同识别，引用槽没有这套记录头。滑窗扫描会带出引用槽残片假命中（参数含 ≥2^23 字节模式或自引用首槽=效果码），按四优先级消歧：①容器（效果码255且参数首槽=技能编号域9999..99999=子技能引用序列）②位==文本CD（语言包说明"CD:N"显式声明）③邻域连续（±44B 处另有有效头，真记录区局部 44B 连续排列）④参数干净（6参数|v|<2^23 且≠3145729）。位=CD回合（bytewise diff 实证），上限放宽至 100（存在 CD=30/40/50 的必杀，旧"位≤5"过滤曾误杀 10004 等 CD>5 记录致效果链缺失）。
    const 候选列 = new Map();
    for (let 偏移 = 4; 偏移 + 44 <= 技能.长度; 偏移++) {
        const 编号 = 技能.读32(偏移);
        if (!编号 || 技能.读16(偏移 + 2) !== 0) continue;
        const 位 = 技能.字节[偏移 + 4];
        const 作用域 = 技能.字节[偏移 + 5];
        const 效果码 = 技能.读16(偏移 + 6);
        if (位 > 100 || 作用域 > 100 || !效果码) continue;
        (候选列.get(编号) || 候选列.set(编号, []).get(编号)).push(偏移);
    }
    const 有效头 = 偏移 => 技能.读32(偏移) !== 0 && 技能.读16(偏移 + 2) === 0 && 技能.字节[偏移 + 4] <= 100 && 技能.字节[偏移 + 5] <= 100 && 技能.读16(偏移 + 6) !== 0;
    const 参数干净 = 偏移 => [10, 14, 18, 22, 26, 30].every(位置 => { const 值 = Math.abs(技能.读i32(偏移 + 位置)); return 值 < 8388608 && 值 !== 3145729; });
    // 假命中磁铁模式否决：参数首槽=效果码自身且其余全 0（如 65331 码104 参数[104,0,0,0,0,0]），为滑窗在引用槽残片上拼出的自引用假记录，真技能参数不会等于自身效果码。
    const 假命中模式 = 偏移 => { const 首 = 技能.读i32(偏移 + 10); return 首 === 技能.读16(偏移 + 6) && [14, 18, 22, 26, 30].every(位置 => 技能.读i32(偏移 + 位置) === 0); };
    // 容器模式：效果码255 且参数首槽=技能编号域（子技能引用序列），必杀多效果容器的强特征（实证 10074/12595/18770）。
    const 容器模式 = 偏移 => 技能.读16(偏移 + 6) === 255 && 技能.读i32(偏移 + 10) > 9999 && 技能.读i32(偏移 + 10) < 100000;
    // 文本CD：语言包说明里 "CD:N"/"冷却N" 显式声明，与位字段同源（渲染值），作消歧判据。
    const 文本CD = 编号 => { const 说 = 文本.get(编号)?.[1] ?? ''; const m = 说.match(/CD\s*[:：]?\s*(\d+)/i) || 说.match(/冷[却卻]\s*[:：]?\s*(\d+)/); return m ? Number(m[1]) : null; };
    const 记录 = new Map();
    const 歧义消歧 = [];
    for (const [编号, 偏移列] of 候选列) {
        const 净 = 偏移列.filter(o => 参数干净(o) && !假命中模式(o));
        const 邻 = 偏移列.filter(o => (o - 44 >= 4 && 有效头(o - 44)) || (o + 88 <= 技能.长度 && 有效头(o + 44)));
        const 有效文本CD = 文本CD(编号);
        const 容 = 净.filter(o => 容器模式(o));
        const 匹CD = 净.filter(o => 有效文本CD !== null && 技能.字节[o + 4] === 有效文本CD);
        const 偏移 = 容[0] ?? 匹CD[0] ?? (净.filter(o => 邻.includes(o))[0]) ?? 净[0] ?? 偏移列[0];
        if (偏移列.length > 1) 歧义消歧.push({ 编号, 候选: 偏移列, 选中: 偏移 });
        const 项 = {
            编号, 偏移, 位: 技能.字节[偏移 + 4], 作用域: 技能.字节[偏移 + 5], 效果码: 技能.读16(偏移 + 6),
            阶段码: 技能.字节[偏移 + 8], 职业码: 技能.字节[偏移 + 9],
            参数: Object.fromEntries([10, 14, 18, 22, 26, 30].map(位置 => [位置, 技能.读i32(偏移 + 位置)])),
            原始记录: 转十六进制(技能.字节.subarray(偏移, 偏移 + 44)),
            文本: 文本.get(编号) || null,
        };
        记录.set(编号, 项);
    }

    const 输出技能 = {};
    const 展开中 = new Set();
    function 展开(编号, 路径列 = []) {
        if (输出技能[编号]) return 输出技能[编号];
        const 项 = 记录.get(编号);
        if (!项) throw new Error(`Skill_C 缺少技能记录：${编号}，路径 ${路径列.join('→')}`);
        if (展开中.has(编号)) return 输出技能[编号];
        展开中.add(编号);
        const 效果 = 翻译记录(项);
        const 结果 = { 编号, 名称: 项.文本?.[0] || `技能${编号}`, 说明: 项.文本?.[1] || '', 偏移: 项.偏移, 位: 项.位, 作用域: 项.作用域, 效果码: 项.效果码, 原始字段: { 阶段码: 项.阶段码, 职业码: 项.职业码, 参数: 项.参数, 原始记录: 项.原始记录 }, 效果 };
        输出技能[编号] = 结果;
        for (const 子编号 of 效果.子技能 || []) 展开(子编号, [...路径列, 编号]);
        展开中.delete(编号);
        return 结果;
    }

    function 技能组字段(组编号, 槽位) {
        const 数量 = 技能组.读32(0);
        if (技能组.长度 !== 4 + 数量 * 44) throw new Error('SkillGroup记录边界不正确');
        for (let 序 = 0; 序 < 数量; 序++) {
            const 偏移 = 4 + 序 * 44;
            if (技能组.读32(偏移) === 组编号) return 技能组.读32(偏移 + 槽位 * 4);
        }
        throw new Error(`SkillGroup缺少技能组：${组编号}`);
    }

    // 敌方被动技能=SkillGroup 槽8-10 直读（原真实敌方资料.json 的被动技能数组即此三槽展开，改造为原包直读；组ID=敌方编号×10+1）。
    const 被动槽 = 组编号 => [技能组字段(组编号, 8), 技能组字段(组编号, 9), 技能组字段(组编号, 10)].filter(Boolean);
    const 颠倒镜普攻 = 技能组字段(432481, 6);
    const SP61普攻 = 技能组字段(422861, 6);
    const 颠倒镜根 = [颠倒镜普攻, ...被动槽(432481), ...敌方规则[43248].filter(规则 => 规则.动作码 !== 9).map(规则 => 规则.技能编号).filter(Boolean)];
    const SP61根 = [SP61普攻, ...被动槽(422861), ...[42286, 52541, 52542, 52543, 52544, 52545].flatMap(编号 => (敌方规则[编号] || []).filter(规则 => 规则.动作码 !== 9).map(规则 => 规则.技能编号).filter(Boolean))];
    const 夏日根 = [...Object.values(夏日行动).flat(), ...夏日机制].map(([, 编号]) => 编号).filter(Boolean);
    for (const 组编号 of [422811, 422821, 422831, 422841, 422851]) 夏日根.push(...[技能组字段(组编号, 6), ...被动槽(组编号)].filter(Boolean));
    // 玩家技能根：SkillGroup 全部组的技能槽（槽0为组ID，槽1-5必杀羁绊档、槽6普攻、槽7队长、槽8-10被动1-3）纳入展开，使玩家技能树进技能字典；解放变体组（编号×10+1..3）部分槽复用已展开技能，展开幂等。缺真实记录头/歧义的槽显式进校核披露，不静默丢弃也不炸树。
    const 技能组根 = [];
    for (let 序 = 0, 组数 = 技能组.读32(0); 序 < 组数; 序++) {
        const 偏移 = 4 + 序 * 44;
        for (let 槽 = 1; 槽 <= 10; 槽++) {
            const 编号 = 技能组.读32(偏移 + 槽 * 4);
            if (编号) 技能组根.push(编号);
        }
    }
    const 技能组缺记录 = [...new Set(技能组根.filter(编号 => !记录.has(编号)))];
    for (const 编号 of new Set([...颠倒镜根, ...SP61根, ...夏日根, ...技能组根.filter(编号 => 记录.has(编号))])) 展开(编号);
    const 未支持 = Object.values(输出技能).filter(项 => 项.效果.类型 === '未支持').map(项 => ({ 编号: 项.编号, 效果码: 项.效果码, 名称: 项.名称, 说明: 项.说明 }));
    const 颠倒镜编号 = [];
    const 收集 = 编号 => { if (颠倒镜编号.includes(编号)) return; 颠倒镜编号.push(编号); for (const 子 of 输出技能[编号].效果.子技能 || []) 收集(子); };
    for (const 编号 of 颠倒镜根) 收集(编号);
    const 颠倒镜缺 = 颠倒镜编号.filter(编号 => 输出技能[编号].效果.类型 === '未支持' || 输出技能[编号].效果.目标.startsWith('未知'));
    if (颠倒镜缺.length) throw new Error(`颠倒镜存在未翻译字段：${颠倒镜缺.map(编号 => `${编号}/${输出技能[编号].效果码}`).join(', ')}`);
    const 夏日缺 = [];
    const 收集夏日 = 编号 => { if (夏日缺.includes(编号)) return; 夏日缺.push(编号); for (const 子 of 输出技能[编号].效果.子技能 || []) 收集夏日(子); };
    for (const 编号 of 夏日根) 收集夏日(编号);
    const 夏日未翻译 = 夏日缺.filter(编号 => 输出技能[编号].效果.类型 === '未支持' || 输出技能[编号].效果.目标.startsWith('未知'));
    if (夏日未翻译.length) throw new Error(`夏日存在未翻译字段：${夏日未翻译.map(编号 => `${编号}/${输出技能[编号].效果.效果码}/${输出技能[编号].效果.目标}`).join(', ')}`);
    for (const 编号 of [22833, 22834, 22835, 22837, 22838]) {
        const 效果 = 输出技能[编号].效果;
        if (效果.持续 !== 9999 || 效果.上限 !== 1) throw new Error(`常驻增益被误译为限回合：${编号} 持续${效果.持续}/上限${效果.上限}`);
    }
    // 全量覆盖审计：按编号去重的全部记录逐条过翻译器统计效果码覆盖度，运行时与构建期共用同一份清单，未知码显式列出而非静默丢弃。
    const 未映射统计 = new Map();
    let 已覆盖 = 0;
    for (const 项 of 记录.values()) {
        if (翻译记录(项).类型 === '未支持') 未映射统计.set(项.效果码, (未映射统计.get(项.效果码) || 0) + 1);
        else 已覆盖++;
    }
    const 覆盖 = {
        记录数: 记录.size, 已覆盖, 未覆盖: 记录.size - 已覆盖,
        效果码总数: new Set([...记录.values()].map(项 => 项.效果码)).size,
        未映射码数: 未映射统计.size,
        未映射清单: [...未映射统计].sort((甲, 乙) => 乙[1] - 甲[1]).map(([效果码, 条数]) => ({ 效果码, 记录数: 条数 })),
    };
    const 结果 = {
        关卡根: { 颠倒镜: 颠倒镜根, 爱你至死不渝SP: SP61根, 夏日尾声: 夏日根 },
        被动: { 颠倒镜: 被动槽(432481), 爱你至死不渝SP: 被动槽(422861), 夏日尾声: Object.fromEntries([42281, 42282, 42283, 42284, 42285].map(编号 => [编号, 被动槽(编号 * 10 + 1)])) },
        技能: 输出技能,
        // 技能组字典：组ID→[槽1..10]（槽1-5必杀羁绊档、槽6普攻、槽7队长、槽8-10被动1-3），供玩家技能通道按组取槽。
        技能组: Object.fromEntries(Array.from({ length: 技能组.读32(0) }, (_, 序) => { const 偏移 = 4 + 序 * 44; return [技能组.读32(偏移), Array.from({ length: 10 }, (_, i) => 技能组.读32(偏移 + (i + 1) * 4))]; })),
        校核: { 颠倒镜记录数: 颠倒镜编号.length, 夏日记录数: 夏日缺.length, 技能组缺记录, 歧义消歧, SP61锚点: { '26647': { 效果: '伤害', 倍率: 2 }, '26649': { 属性: '造成伤害', 数值: 0.1, 上限: 6 }, '26650': { 属性: '受到伤害', 数值: 0.1, 上限: 6 }, '26658': { 异常: '沉默', 持续: 3 }, '26662': { 异常: '睡眠', 持续: 2, 受伤增加: 1 } }, 未支持, 覆盖 },
    };
    const 锚 = 结果.校核.SP61锚点;
    for (const [编号, 预期] of Object.entries(锚)) {
        const 实际 = 输出技能[编号]?.效果;
        for (const [字段, 值] of Object.entries(预期)) if (字段 !== '效果' && 实际?.[字段] !== 值) throw new Error(`SP61字段锚点失败：${编号}.${字段}=${实际?.[字段]}，应为${值}；原始偏移${输出技能[编号]?.偏移}，参数${JSON.stringify(输出技能[编号]?.原始字段?.参数)}`);
    }
    return 结果;
}
