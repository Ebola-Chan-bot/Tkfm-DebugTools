export const 真实角色目录 = 真实目录.filter(单位 => (单位.稀有度 ?? 单位.资料?.split('-')[0]) === 'SSR');
const 编号索引 = new Map(真实角色目录.map(单位 => [单位.编号, 单位]));
const 技能索引 = new Map(真实技能.filter(单位 => 编号索引.has(单位.编号)).map(单位 => [单位.编号, 单位]));
const 规范名称 = 输入 => String(输入 ?? '').normalize('NFKC').toLocaleLowerCase().replace(/[\s\p{P}]/gu, '');

function 匹配名称(单位) {
    const 已有 = 角色库.find(项 => 项.编号 === 单位.编号);
    return [...单位.别名, 单位.全名, 已有?.名称, 已有?.全名].filter(Boolean).map(规范名称);
}

export function 获取真实角色(编号) {
    return 编号索引.get(编号);
}

