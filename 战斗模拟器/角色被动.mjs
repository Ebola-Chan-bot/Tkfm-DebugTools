// 队长技选择：条件命中取匹配字段，否则取默认字段；无表项按常规队长技。
export function 领队技能列(队长, 接口) {
    const 环 = { 状态: null, 钩子单位: 队长, 主体: 队长, 队长, 专属编号: 接口.专属编号, 接口 };
    for (const 入口 of 被动表) {
        if (入口.时机 !== '领队技能列' || 环.专属编号(队长) !== 入口.编号) continue;
        return 条件成立(入口.条件, 环) ? 队长[入口.选择.匹配字段] : 队长[入口.选择.默认字段];
    }
    return 队长.队长;
}

