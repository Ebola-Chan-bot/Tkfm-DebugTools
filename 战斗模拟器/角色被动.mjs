// 技能列选择：条件命中后按尝试链取首个存在字段，否则回退传入技能列。
export function 技能列被动(状态, 单位, 动作, 技能列, 接口) {
    const 环 = { 状态, 钩子单位: 单位, 主体: 单位, 行动者: 单位, 队长: 状态.队伍[0], 动作, 专属编号: 接口.专属编号, 接口 };
    for (const 入口 of 被动表) {
        if (入口.时机 !== '技能列' || 环.专属编号(单位) !== 入口.编号) continue;
        if (!条件成立(入口.条件, 环)) continue;
        for (const 档 of 入口.选择.尝试) {
            if (档.条件 && !条件成立(档.条件, 环)) continue;
            const 值 = 单位[档.字段.replace('{动作}', 动作)];
            if (值) return 值;
        }
        return 技能列;
    }
    return 技能列;
}

