// 计数谓词：{ 键, ≥ / = / ≤ } 与单位计数表比对，缺省按 0 计。
function 计数满足(单位, 条件) {
    const 值 = 单位?.计数?.[条件.键] || 0;
    return (条件['≥'] === undefined || 值 >= 条件['≥'])
        && (条件['='] === undefined || 值 === 条件['='])
        && (条件['≤'] === undefined || 值 <= 条件['≤']);
}

function 队伍计数(队伍, 属性键, 属性值) {
    return (队伍 || []).filter(单位 => 单位[属性键] === 属性值).length;
}

// 声明式条件求值：主体谓词（解放/羁绊/星级/位置/属性/职业/计数/存活）、行动者谓词、接收者谓词、队伍聚合谓词与状态谓词。
function 条件成立(条件, 环) {
    for (const [键, 期望] of Object.entries(条件 || {})) {
        const 主 = 环.主体, 行 = 环.行动者, 接 = 环.接收者;
        if (键 === '解放' && 主.解放 !== 期望) return false;
        else if (键 === '解放>' && !(主.解放 > 期望)) return false;
        else if (键 === '羁绊' && 主.羁绊 !== 期望) return false;
        else if (键 === '羁绊≥' && !(主.羁绊 >= 期望)) return false;
        else if (键 === '星级' && 主.星级 !== 期望) return false;
        else if (键 === '星级≥' && !(主.星级 >= 期望)) return false;
        else if (键 === '位置' && 主.位置 !== 期望) return false;
        else if (键 === '位置>' && !(主.位置 > 期望)) return false;
        else if (键 === '存活' && (主.生命 > 0) !== 期望) return false;
        else if (键 === '属性' && !期望.includes(主.属性)) return false;
        else if (键 === '职业' && 主.职业 !== 期望) return false;
        else if (键 === '动作' && (期望 === '非普攻' ? 环.动作 === '普攻' : 环.动作 !== 期望)) return false;
        else if (键 === '计数' && !计数满足(主, 期望)) return false;
        else if (键 === '行动者属性' && !期望.includes(行?.属性)) return false;
        else if (键 === '行动者职业' && 行?.职业 !== 期望) return false;
        else if (键 === '行动者动作' && (期望 === '非普攻' ? 环.动作 === '普攻' : 环.动作 !== 期望)) return false;
        else if (键 === '行动者位置=' && 行?.位置 !== 期望) return false;
        else if (键 === '行动者位置>' && !(行?.位置 > 期望)) return false;
        else if (键 === '行动者不同主体' && 期望 && 行 === 主) return false;
        else if (键 === '行动者计数' && !计数满足(行, 期望)) return false;
        else if (键 === '接收属性' && !期望.includes(接?.属性)) return false;
        else if (键 === '接收非触发治疗' && 期望 && 环.触发治疗) return false;
        else if (键 === '接收非队长' && 期望 && 接 === 环.队长) return false;
        else if (键 === '接收不同主体' && 期望 && 接 === 主) return false;
        else if (键 === '队伍职业' && 队伍计数(环.队伍, '职业', 期望.职业) < (期望['≥'] ?? 1)) return false;
        else if (键 === '队伍属性' && 队伍计数(环.队伍, '属性', 期望.属性) < (期望['≥'] ?? 1)) return false;
        else if (键 === '无领取者' && 期望 && 环.状态.VIP领取者) return false;
    }
    return true;
}

// 值表达式求值：纯数值直用；带基准的按基准取量再乘系数（护盾比攻击=护盾/下限1攻击，与炸盾实测公式同形）。
function 数值求值(表达, 环) {
    if (typeof 表达 === 'number') return 表达;
    const 来源 = 环.动作来源 || 环.主体;
    if (表达.基准 === '主体当前攻击') return 环.接口.当前攻击(环.主体) * 表达.系数;
    if (表达.基准 === '行动者当前攻击') return 环.接口.当前攻击(环.行动者) * 表达.系数;
    if (表达.基准 === '主体生命上限') return 环.主体.生命上限 * 表达.系数;
    if (表达.基准 === '接收生命上限') return 环.接收者.生命上限 * 表达.系数;
    if (表达.基准 === '护盾比攻击') return 环.接口.当前护盾(来源) / Math.max(1, 环.接口.当前攻击(来源)) * 表达.系数;
    throw new Error(`未知值基准：${表达.基准}`);
}

// 接收者解析：接收者（钩子目标）/主体/队长/行动者/全体（选目标全体）/全体存活/首领。
function 解析接收(标记, 环) {
    if (标记 === '接收者') return [环.接收者];
    if (标记 === '主体') return [环.主体];
    if (标记 === '队长') return [环.队长];
    if (标记 === '行动者') return [环.行动者];
    if (标记 === '全体') return 环.接口.选目标(环.状态, 环.行动者, '全体');
    if (标记 === '全体存活') return 环.队伍.filter(项 => 项.生命 > 0);
    if (标记 === '首领') return [环.状态.首领];
    throw new Error(`未知接收标记：${标记}`);
}

// 动作分发：设置冷却/执行效果列/登记领取者/记录/增益/治疗/伤害/叠计数/清护盾，全部经接口回调引擎助手。
function 执行动作(动作, 环) {
    const 接 = 环.接口;
    const 来源 = 环.动作来源 || 环.主体;
    const 名称 = String(动作.名称 || '').replace('{动作}', 环.动作 ?? '');
    if (动作.类型 === '设置冷却') {
        for (const 档 of 动作.档位) {
            if (!档.条件 || 条件成立(档.条件, 环)) { 环.主体.冷却 = 档.值; break; }
        }
    } else if (动作.类型 === '执行效果列') {
        const 效果列 = 动作.字段 ? (环.主体[动作.字段] || []) : 动作.效果;
        接.执行效果列(环.状态, 来源, 效果列, 动作.阶段);
    } else if (动作.类型 === '登记领取者') {
        环.状态.VIP领取者 = 解析接收('行动者', 环)[0].编号;
    } else if (动作.类型 === '记录') {
        接.记录(环.状态, 动作.类别, 动作.内容, 动作.数值 ?? null, 解析接收(动作.位置 || '主体', 环)[0].位置);
    } else {
        for (const 接收 of 解析接收(动作.接收 || 环.接收标记, 环)) {
            if (!接收) continue;
            if (动作.类型 === '增益') {
                const 数值 = 数值求值(动作.数值, 环);
                if (动作.上限 !== undefined) 接.添加增益(接收, 动作.属性, 数值, 动作.持续, 来源, 名称, 动作.上限);
                else 接.添加增益(接收, 动作.属性, 数值, 动作.持续, 来源, 名称);
            } else if (动作.类型 === '治疗') {
                接.执行治疗(环.状态, 来源, 接收, 数值求值(动作.数值, 环), false, true);
            } else if (动作.类型 === '伤害') {
                接.造成伤害(环.状态, 来源, 数值求值(动作.数值, 环), 动作.类别 || '触发', 名称);
            } else if (动作.类型 === '叠计数') {
                接收.计数[动作.键] = Math.min(动作.上限 ?? Number.MAX_SAFE_INTEGER, (接收.计数[动作.键] || 0) + (动作.加数 || 1));
            } else if (动作.类型 === '清护盾') {
                接收.护盾 = [];
            } else throw new Error(`未知被动动作：${动作.类型}`);
        }
    }
}

// 按时机派发：定位主体（钩子单位/队长/存活持有者/接收者），核对持有编号与条件后执行动作；重复字段按属性组数放大量。
function 派发(状态, 时机, 环境) {
    const 队伍 = 环境.队伍 || 状态.队伍;
    for (const 入口 of 被动表) {
        if (入口.时机 !== 时机) continue;
        const 主体 = 入口.主体 === '队长' ? 环境.队长
            : 入口.主体 === '接收者' ? 环境.接收者
            : 入口.主体 === '存活持有者' ? 队伍.find(单位 => 环境.专属编号(单位) === 入口.编号 && 单位.生命 > 0)
            : 环境.钩子单位;
        if (!主体 || 环境.专属编号(主体) !== 入口.编号) continue;
        const 环 = { ...环境, 状态, 队伍, 主体, 动作来源: 入口.动作来源 === '行动者' ? 环境.行动者 : 主体, 接收标记: 入口.接收 };
        if (!条件成立(入口.条件, 环)) continue;
        let 次数 = 1;
        if (入口.重复?.属性组) 次数 = 入口.重复.属性组.filter(([属性, 人数]) => 队伍计数(队伍, '属性', 属性) >= 人数).length;
        for (let i = 0; i < 次数; i++) for (const 动作 of 入口.动作 || []) 执行动作(动作, 环);
    }
}

