// 对应原包架构里「角色行为来自角色数据表」的边界：核心引擎只在固定钩子点调用本模块，不硬编码任何角色编号；角色行为全部下沉到 角色被动表.json，本模块只含表驱动的条件求值与动作分发。数值计算走战斗数值.mjs 内核，效果施加经接口回调引擎助手，故无循环依赖。

