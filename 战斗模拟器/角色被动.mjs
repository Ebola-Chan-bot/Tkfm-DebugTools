// 角色被动.mjs —— 角色专属被动、队长技与联动效果，与核心战斗引擎分离。
// 对应原包架构里「角色行为来自角色数据表」的边界：核心引擎只在固定钩子点调用本模块，不硬编码任何角色编号。本模块只含角色专属判定与效果施加；数值计算走战斗数值.mjs 内核，效果施加与目标选择经接口回调引擎助手，故无循环依赖。逻辑自 战斗引擎.mjs 原样迁出（纯代码搬家，行为不变），逐个角色编号集中于此，便于后续整体下沉为数据表。

// 钩子接口由引擎构造后传入，包含所需助手：添加增益/当前攻击/当前护盾/造成伤害/执行治疗/执行效果列/选目标/专属编号/加成/记录。

// 战斗开始·解放初始：10006 解放2 时执行解放初始效果列（在初始效果列之后、逐单位）。
export function 解放初始被动(状态, 单位, 接口) {
    const { 专属编号, 执行效果列 } = 接口;
    if (专属编号(单位) === 10006 && 单位.解放 === 2) 执行效果列(状态, 单位, 单位.解放初始 || [], '解放初始');
}

// 战斗开始·初始冷却：10006 与 10053 的冷却随解放/羁绊取档（在生命初始化增益之后、逐单位）。
export function 初始冷却被动(状态, 单位, 接口) {
    const { 专属编号 } = 接口;
    if (专属编号(单位) === 10006) 单位.冷却 = 单位.解放 ? (单位.羁绊 >= 3 ? 4 : 5) : (单位.羁绊 === 5 ? 4 : 5);
    if (专属编号(单位) === 10053) 单位.冷却 = 单位.羁绊 >= 3 ? 4 : 5;
}

// 战斗开始·队长受盾限制：10133 队伍≥2辅助者时队长受盾变化 -6。
export function 队长受盾被动(状态, 队长, 队伍, 接口) {
    const { 专属编号, 添加增益 } = 接口;
    if (专属编号(队长) === 10133 && 队伍.filter(项 => 项.职业 === '辅助者').length >= 2) 添加增益(队长, '受盾变化', -6, 9999, 队长, '奈奈美队长受盾限制');
}

// 队长技选择：10006 解放2用解放队长，否则常规队长技。
export function 领队技能列(队长, 接口) {
    const { 专属编号 } = 接口;
    return 专属编号(队长) === 10006 && 队长.解放 === 2 ? 队长.解放队长 : 队长.队长;
}

// 防御减伤附加：10006 独有 +10% 防御减伤，供伤害槽与承伤槽共用。
export function 防御减伤附加(目标, 接口) {
    return 接口.专属编号(目标) === 10006 ? .10 : 0;
}

// 技能列选择：10006 解放后改用解放技能列（部分解放优先）。
export function 技能列被动(状态, 单位, 动作, 技能列, 接口) {
    const { 专属编号 } = 接口;
    if (专属编号(单位) === 10006 && 单位.解放 > 0) return (单位.解放 === 1 ? 单位[`部分解放${动作}`] : null) || 单位[`解放${动作}`] || 技能列;
    return 技能列;
}

// 行动后置技能列选择：10006 解放后用解放行动后。
export function 后置技能列(状态, 单位, 接口) {
    const { 专属编号 } = 接口;
    return 专属编号(单位) === 10006 && 单位.解放 > 0 ? 单位.解放行动后 : 单位.行动后;
}

// 治疗增幅附加：10190 魔力≥2 时治疗 +50%。
export function 治疗增幅附加(来源, 接口) {
    const { 专属编号 } = 接口;
    return 专属编号(来源) === 10190 && 来源.计数.魔力 >= 2 ? .50 : 0;
}

// 被治疗触发：10190 守护众人叠层、10085 花魁受疗联动、10190 丧巴被治疗永眠。
export function 被治疗被动(状态, 目标, 触发治疗, 接口) {
    const { 专属编号, 添加增益, 当前攻击, 记录 } = 接口;
    const 队长 = 状态.队伍[0];
    if (专属编号(队长) === 10190) {
        目标.计数.守护 = Math.min(40, (目标.计数.守护 || 0) + 1);
        添加增益(目标, '触发增幅', .0225, 9999, 队长, '守护众人', 40);
    }
    const 花魁 = 状态.队伍.find(单位 => 专属编号(单位) === 10085 && 单位.生命 > 0);
    if (花魁 && !触发治疗) {
        添加增益(目标, '攻击比例', .125, 2, 花魁, '花魁受疗加攻');
        if (花魁.星级 >= 4) 添加增益(目标, '造成伤害', .05, 2, 花魁, '花魁受疗增伤');
        if (花魁.位置 === 0 && ['火', '暗'].includes(目标.属性)) {
            添加增益(目标, '必杀伤害', .075, 2, 花魁, '花魁队长受疗必杀');
            添加增益(目标, '普攻伤害', .10, 2, 花魁, '花魁队长受疗普攻');
        }
    }
    if (专属编号(目标) === 10190) {
        const 魔力 = 目标.计数.魔力 || 0;
        for (const 单位 of 状态.队伍.filter(项 => 项.生命 > 0)) {
            添加增益(单位, '触发增幅', .06, 9999, 目标, '凯萨的永眠', 10);
            添加增益(单位, '攻击追击', .30, 1, 目标, '凯萨的永眠追击');
            if (目标.星级 >= 5) 添加增益(单位, '造成伤害', .015, 9999, 目标, '信守约定', 10);
            if (魔力 >= 1 && ['水', '光'].includes(单位.属性)) 添加增益(单位, '造成伤害', .10, 1, 目标, '魔力丧失');
            if (魔力 === 3 && 单位.编号 !== 目标.编号) 添加增益(单位, '攻击固定', 当前攻击(目标) * .06, 1, 目标, '魔力丧失加攻');
        }
        记录(状态, '触发', '丧巴被治疗：永眠与信守约定叠层', null, 目标.位置);
    }
}

// 行动后被动：非防御/待机行动结束后的角色联动（守护治疗、花魁火暗治疗、商狐交易、特别菜单、奈奈美炸盾）。
export function 行动后被动(状态, 单位, 动作, 接口) {
    const { 专属编号, 执行治疗, 造成伤害, 执行效果列, 选目标, 添加增益, 当前攻击, 当前护盾 } = 接口;
    const 队长 = 状态.队伍[0];
    if (专属编号(队长) === 10190) {
        const 属性组数 = ['水', '光'].filter(属性 => 状态.队伍.filter(角色 => 角色.属性 === 属性).length >= 2).length;
        for (let 次数 = 0; 次数 < 属性组数; 次数++) for (const 目标 of 选目标(状态, 单位, '全体')) 执行治疗(状态, 单位, 目标, 目标.生命上限 * .01, false, true);
        if ((单位.计数.守护 || 0) >= 20) 造成伤害(状态, 单位, .20, '触发', '守护众人二十层');
        if (单位.计数.守护 === 40) 造成伤害(状态, 单位, .20, '触发', '守护众人四十层');
    }
    if (专属编号(队长) === 10085 && ['火', '暗'].includes(单位.属性)) for (const 目标 of 选目标(状态, 单位, '全体')) 执行治疗(状态, 单位, 目标, 当前攻击(单位) * .05, false, true);
    if (专属编号(队长) === 10062 && 单位.编号 !== 队长.编号) {
        添加增益(队长, '攻击比例', .03, 9999, 队长, '商狐交易加攻', 15);
        添加增益(队长, '治疗增幅', .02, 9999, 队长, '商狐交易治疗', 15);
    }
    if (专属编号(队长) === 10053 && 单位.职业 === '攻击者') 添加增益(单位, 动作 === '普攻' ? '必杀伤害' : '普攻伤害', 动作 === '普攻' ? .15 : .50, 9999, 队长, `特别菜单${动作}`, 动作 === '普攻' ? 2 : 1);
    if (专属编号(队长) === 10133) {
        if (单位.位置 > 0) 执行效果列(状态, 单位, [{ 类型: '护盾', 倍率: .30, 基准: '当前攻击', 目标: '首位', 持续: 1, 名称: '钱没有消失' }], '队长联动');
        else {
            造成伤害(状态, 单位, 当前护盾(单位) / Math.max(1, 当前攻击(单位)) * (动作 === '普攻' ? .55 : .60), '触发', '奈奈美炸盾');
            单位.护盾 = [];
        }
    }
}

// 防御行动被动：10062 VIP 联动、10168 拉尤防御减伤受疗。
export function 防御行动被动(状态, 单位, 接口) {
    const { 专属编号, 添加增益 } = 接口;
    const 队长 = 状态.队伍[0];
    const 商狐 = 状态.队伍.find(角色 => 专属编号(角色) === 10062 && 角色.星级 >= 5 && 角色.生命 > 0);
    if (商狐 && 单位.编号 !== 商狐.编号 && !状态.VIP领取者) {
        状态.VIP领取者 = 单位.编号;
        for (const [属性, 值] of [['攻击比例', .30], ['造成伤害', .15], ['必杀伤害', .15]]) 添加增益(单位, 属性, 值, 9999, 商狐, `VIP:${属性}`);
    }
    if (专属编号(队长) === 10168 && 状态.队伍.filter(角色 => 角色.属性 === '风').length >= 4) {
        添加增益(单位, '受伤变化', -.10, 1, 队长, '拉尤防御减伤');
        添加增益(单位, '受疗增加', .30, 4, 队长, '拉尤防御受疗');
    }
}

// 回合开始被动：10190 丧巴队长每回合给首领水光易伤。
export function 回合易伤被动(状态, 接口) {
    const { 专属编号, 添加增益 } = 接口;
    const 队长 = 状态.队伍[0];
    if (专属编号(队长) === 10190 && 队长.生命 > 0) 添加增益(状态.首领, '水光易伤', .02, 9999, 队长, '丧巴队长回合易伤', 10);
}
