    状态.攻击目标 = 状态.敌人.length > 1 ? 目标位置 : 0;
    记录(状态, '行动', `${单位.位置 + 1} · ${单位.名称} · ${动作}`);
    单位.已行动 = true;
    状态.我方动作计数 ??= { 普攻: 0, 必杀: 0, 防御: 0 };
    状态.我方动作计数[动作] = (状态.我方动作计数[动作] || 0) + 1;
    单位.防御 = 动作 === '防御';
    if (动作 === '必杀') 单位.冷却剩余 = 单位.冷却;
    if (动作 === '必杀') 派发敌方必杀(状态, 单位);
    let 技能列 = (动作 === '防御' ? 单位.防御技能 : 单位[动作]) || [];
    if (专属编号(单位) === 10006 && 单位.解放 > 0) 技能列 = (单位.解放 === 1 ? 单位[`部分解放${动作}`] : null) || 单位[`解放${动作}`] || 技能列;
