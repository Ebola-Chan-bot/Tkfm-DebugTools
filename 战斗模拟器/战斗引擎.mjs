function 有限正数(数值, 名称) {
    if (!Number.isFinite(数值) || 数值 <= 0) throw new Error(`${名称}必须为正数`);
    return 数值;
}

function 档位(数值, 单位) {
    return Array.isArray(数值) ? 数值[单位.羁绊 - 1] : 数值;
}


function 属性倍率(来源, 目标) {
    if (!来源.属性 || !目标.属性) return 1;
    const 克制 = { [枚举.火]: 枚举.风, [枚举.风]: 枚举.水, [枚举.水]: 枚举.火, [枚举.光]: 枚举.暗, [枚举.暗]: 枚举.光 };
    const 修正 = 克制[来源.属性] === 目标.属性 ? .5 : [枚举.火, 枚举.水, 枚举.风].includes(来源.属性) && 克制[目标.属性] === 来源.属性 ? -.25 : 0;
    return 1 + 修正 * Math.max(0, 1 + 加成(来源, 枚举.相克抵消)) * Math.max(0, 1 - 加成(目标, 枚举.属性相克减少));
}

function 按动作批次(状态, 执行, 动作类别 = 枚举.触发) {
    const 上一批次 = 状态.当前伤害批次 ?? null;
    const 上一类别 = 状态.当前动作类别 ?? null;
    状态.动作批次序 = (状态.动作批次序 || 0) + 1;
    状态.当前伤害批次 = 状态.动作批次序;
    状态.当前动作类别 = 动作类别;
    try { return 执行(); }
    finally { 状态.当前伤害批次 = 上一批次; 状态.当前动作类别 = 上一类别; }
}

function 派发受击(状态, 目标, 类别) {
    const 批次 = 状态.当前伤害批次;
    if (批次 !== null && 批次 !== undefined && 目标.最近受击批次 === 批次) return;
    if (批次 !== null && 批次 !== undefined) 目标.最近受击批次 = 批次;
    const 被击时机 = ({ [枚举.普攻]: 枚举.被普攻, [枚举.必杀]: 枚举.被必杀 })[类别] ?? null;
    派发角色触发(状态, 目标, 被击时机 ? [枚举.被攻击, 被击时机] : 枚举.被攻击);
    派发原包触发(状态, 目标, 被击时机 ? [枚举.被攻击, 被击时机] : 枚举.被攻击);
    if (类别 === 枚举.普攻) { 派发角色触发(状态, 目标, 枚举.被普攻); 派发原包触发(状态, 目标, 枚举.被普攻); }
    目标.效果 = 目标.效果.filter(项 => 项.受击限次 === undefined || --项.受击限次 > 0);
}

function 立即派发受击(状态, 事件) {
    const 原来源 = 状态.当前受击来源 ?? null;
    const 原归属 = 状态.当前日志归属;
    if (事件.归属 !== undefined && 事件.归属 !== null) 状态.当前日志归属 = 事件.归属;
    状态.当前受击来源 = 事件.来源;
    try { 派发受击(状态, 事件.目标, 事件.类别); }
    finally { 状态.当前受击来源 = 原来源; 状态.当前日志归属 = 原归属; }
}

function 结算待受击(状态) {
    let 深度 = 0;
    while (状态.待受击?.length) {
        if (++深度 > 12) throw new Error('受击事件链超过模型深度限制');
        const 队列 = 状态.待受击;
        状态.待受击 = [];
        for (const 事件 of 队列) 立即派发受击(状态, 事件);
    }
    delete 状态.待受击;
}

