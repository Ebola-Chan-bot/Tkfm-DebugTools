function 敌方承伤(状态, 目标, 数值, 类别 = null, 伤害来源 = null) {
    const 阶段锁血 = (目标.锁血阈值 || []).map(项 => Math.ceil(目标.生命上限 * 项.比例));
    const 最低 = Math.max(0, ...阶段锁血, 加成(目标, 枚举.锁血) > 0 ? Math.max(1, Math.ceil(目标.生命上限 * .0001)) : 0);
    const 有效 = Math.min(Math.max(0, 目标.生命 - 最低), Math.max(0, Math.floor(数值)));
    目标.生命 -= 有效;
    if (有效 > 0) 解除睡眠(目标);
    if (目标.生命 === 0) 记录(状态, 枚举.倒下, `${目标.名称}被击破`, null, 目标.名称);
    if (类别 && 类别 !== 枚举.持续 && 目标.蓄力) {
        目标.蓄力.命中 = (目标.蓄力.命中 || 0) + 1;
        if (目标.蓄力.命中 >= 目标.蓄力.解除次数) {
            目标.蓄力 = null;
            记录(状态, 枚举.机制, `${目标.名称}蓄力解除`);
        }
    }
    if (类别 && 类别 !== 枚举.持续) {
        const 事件 = { 目标, 类别, 来源: 伤害来源?.编号 ?? null, 归属: 伤害来源 && 状态.队伍.includes(伤害来源) ? 状态.最近我方日志归属 : 状态.当前日志归属 };
        // 原包在一次普攻或必杀的主体、追加和发动效果结束后才调用 boss.hit，不能让主体受击效果提前影响同次行动的后续伤害。
        if (状态.阶段 === 枚举.我方 && [枚举.普攻, 枚举.必杀].includes(状态.当前动作类别)) (状态.待受击 ??= []).push(事件);
        else 立即派发受击(状态, 事件);
    }
    // AI 事件时点=伤害后（实测校准常量）：每段伤害结算后立即检查AI条件，不等整个行动结束。
    自动事件(状态, 枚举.伤害后);
    return 有效;
}

// 从角色增益数组聚合出 BattleCalculator 需要的增益槽：攻守各一份，字段对应 TBattleCharBonusProperty 的语义槽。
function 伤害增益槽(状态, 来源, 目标, 类别) {
    let 技能增幅, 技能易伤;
    switch (类别) {
        case 枚举.普攻: case 枚举.普攻追加: 技能增幅 = 加成(来源, 枚举.普攻伤害); 技能易伤 = 加成(目标, 枚举.普攻易伤); break;
        case 枚举.必杀: case 枚举.必杀追加: 技能增幅 = 加成(来源, 枚举.必杀伤害); 技能易伤 = 加成(目标, 枚举.必杀易伤); break;
        case 枚举.触发: 技能增幅 = 加成(来源, 枚举.必杀伤害) + 加成(来源, 枚举.触发增幅) + 加成(来源, 枚举.触发伤害); 技能易伤 = 加成(目标, 枚举.必杀易伤) + 加成(目标, 枚举.触发易伤); break;
        default: 技能增幅 = 加成(来源, 枚举.持续伤害增幅); 技能易伤 = 加成(目标, 枚举.持续伤害易伤);
    }
    // 汇编 GetPropertyDamageRate(F5) 只读被攻击方按攻方属性索引的属性易伤槽(B+0x5f0..0x6b0)，不含攻方自身属性易伤；水光易伤为守方特例槽。攻方属性易伤(尤妮思队长技给风队员挂载)非本槽，待另行映射到正确槽位。
    const 属性增幅 = 加成(目标, 易伤键(来源.属性)) + ([枚举.水, 枚举.光].includes(来源.属性) ? 加成(目标, 水光易伤) : 0);
    const 分类区 = 技能增幅 + 技能易伤 + 加成(目标, 职业易伤键(来源.职业)) + 加成(目标, 来源易伤键(来源.编号)) + (处于防御(目标) ? 加成(来源, 枚举.防御目标增伤) : 0);
    const 防御作用中 = 处于防御(目标);
    return {
        变化率: 0,
        攻槽: { 属性: 来源.属性, 造成伤害: 加成(来源, 枚举.造成伤害), 属性加成: 加成(来源, 枚举.相克抵消), 破防加成: 0 },
        // 汇编 F3=1+克制率×(1+属性加成)，属性加成=攻守属性加成之和：攻方相克抵消、守方属性相克减少取负。分类区（技能/职业/来源增伤易伤）按汇编 kind 门控归入 F2 其他加成，F1 变化率是技能自带参数（本模型未单列，故为 0）。
        守槽: {
            属性: 目标.属性,
            受到伤害: 加成(目标, 枚举.受到伤害),
            属性加成: -加成(目标, 枚举.属性相克减少),
            其他加成: { 1: 分类区 },
            属性受击加成: { [来源.属性]: 属性增幅 },
            防御作用中, 防御减伤率: 防御基准减伤, 防御加成: 加成(目标, 枚举.防御减伤),
            破防作用中: false, 破防率: 0, 伤害变化率: 0,
        },
    };
}

function 造成伤害(状态, 来源, 倍率, 类别, 名称, 目标 = 状态.敌人[状态.攻击目标], 真实 = false, 指定基础 = null) {
    if (!(倍率 > 0) && !(指定基础 > 0)) return;
    if (!目标 || 目标.生命 <= 0) return;
    const 槽 = 伤害增益槽(状态, 来源, 目标, 类别);
    const 基础值 = 指定基础 ?? 当前攻击(来源) * 倍率;
    // 真伤与普伤均走 BattleCalculator 内核：真伤=基础×F6(仅防御区)，普伤乘 F1..F9 全链，均按汇编 GetDamageValue。
    const 数值 = 计算伤害值({
        基础值, 倍率: 1,
        变化率: 槽.变化率, 固定增减: 0,
        攻槽: 槽.攻槽, 守槽: 槽.守槽, 类别: 1,
        真实,
    });
    const 有效 = 敌方承伤(状态, 目标, 数值, 类别, 来源);
    状态.累计伤害 += 有效;
    状态.本回合.伤害 += 有效;
    来源.统计.伤害 += 有效;
    记录(状态, 枚举.伤害, `${来源.名称} → ${目标.名称} · ${名称}`, 有效, 目标.名称, 来源);
    if (类别 !== 枚举.持续 && 加成(来源, 枚举.吸血) > 0 && 来源.生命 > 0) 执行治疗(状态, 来源, 来源, 有效 * 加成(来源, 枚举.吸血), false, true);
    return 有效;
}

function 被治疗触发(状态, 目标, 触发治疗, 持续型 = false) {
    // 汇编+数据表双证据：持续治疗（码9/115）的 SkillEffect 行首字节 type=0x0b（回合后状态效果族），与 BattleCalculator.CalculateAfterRoundSkillResult:0x2174ad0 的 `cmp w8,#0xb` 同型校验互证；该族由 BattleSys.GetAfterRoundSkillData(0x22aa2dc，调度方 BattlePhaseCtrl.Emulator_CheckPhase) 经 TCharBattleData.SetData / UpdateCharData / CalculateShieldData 直接落账——全镜像 bl 扫描确认此链无 CalculateEffResult / GetHealValue / GetTriggerBeHealedSkill / UpdateTriggerSkillData / DoTriggerSkill / UseSkill 调用，被治疗/被攻击触发派发只存在于 CalculateEffResult（技能效果执行）内。∴ 持续型治疗（状态 tick）不派发任何被治疗触发（三通道全跳过）；持续伤害 tick 侧此前已用 触发受击=false 同向对齐。
    if (持续型) return;
    // 汇编依据（battle_asm）：被治疗触发派发点 CalculateEffResult:0x21864b8（bl GetTriggerBeHealedSkill → UpdateTriggerSkillData）前置三重门 0x218644c-0x2186468：①执行上下文标识 == -1 哨兵（普攻动作 SelectCharToAttack 传立即数 -1，触发技执行路径传真实触发来源标识）②反篡改探针位 == 0（0x215a8fc 自校验谓词，正常运行恒 0）③效果未被免疫（ChkIsImmune 门 w28≠0），三者全真才派发；GetTriggerBeHealedSkill 循环体内仅 ChkIsCharCanDoTriggerAction / ChkIsProbabilityTrigger / 时机匹配，无逐条排除标志，排除是上下文级全局门。∴ 触发技的治疗效果不派发任何被治疗触发。模拟器判据：治疗执行发生在触发派发链内（角色触发深度 / 原包触发深度 / 治疗事件深度 > 0，分别对应模型触发技、原包触发技、被治疗触发自身的表动作与子技能）即为触发技治疗，整段跳过；跳过发生在同批次去重之前，不消耗批次槽位。
    if ((状态.角色触发深度 || 0) > 0 || (状态.原包触发深度 || 0) > 0 || (状态.治疗事件深度 || 0) > 0) return;
    const 类别 = 持续型 ? 枚举.持续 : 触发治疗 ? 枚举.触发 : '普通';
    const 批次 = 状态.当前伤害批次;
    if (批次 !== null && 批次 !== undefined) {
        目标.最近治疗批次 ??= {};
        if (目标.最近治疗批次[类别] === 批次) return;
        目标.最近治疗批次[类别] = 批次;
    }
    if (状态.治疗事件深度 >= 8) throw new Error('治疗触发深度超出模型限制');
    状态.治疗事件深度++;
    派发角色触发(状态, 目标, 枚举.被治疗);
    派发原包触发(状态, 目标, 枚举.被治疗);
    状态.治疗事件深度--;
}

function 派发角色触发(状态, 单位, 时机, 行动前有效 = null) {
    if (!单位.触发?.length || 单位.生命 <= 0) return;
    if ((状态.角色触发深度 || 0) >= 12) throw new Error('角色触发链超过模型深度限制');
    状态.角色触发深度 = (状态.角色触发深度 || 0) + 1;
    try {
        const 时机列 = Array.isArray(时机) ? 时机 : [时机];
        // 攻击者在本次动作中新授予的受击监听不得追溯触发本次攻击；原始来源用于穿过授予效果的接收者，后续攻击与其他来源监听不受影响。
        const 列表 = 单位.触发.filter(项 => 时机列.includes(项.时机) && (!行动前有效 || 行动前有效.has(项)) && !(项.时机 === 枚举.被攻击 && 项.注册批次 === 状态.当前伤害批次 && (项.原始来源 ?? 项.来源) === 状态.当前受击来源) && 项.剩余 > 0 && 项.次数 !== 0 && (!项.次数组 || 单位.触发组?.[项.次数组] > 0) && !来源被免疫(单位, 项) && 检查效果判定(状态, 单位, 项.判定)).sort((甲, 乙) => Number(甲.效果方式 !== 枚举.追加) - Number(乙.效果方式 !== 枚举.追加) || 时机列.indexOf(甲.时机) - 时机列.indexOf(乙.时机));

        const 已消耗组 = new Set();
        for (const 项 of 列表) {
            if (项.周期 && (状态.回合 === 1 || (状态.回合 - 1) % 项.周期 !== 0)) continue;
            if (项.指定回合 && 状态.回合 !== 项.指定回合) continue;
            if (项.指定回合集 && !项.指定回合集.includes(状态.回合)) continue;
            if (!判定概率(状态, 项.概率 ?? 1)) continue;
            if (项.次数组 && !已消耗组.has(项.次数组)) {
                单位.触发组[项.次数组]--;
                已消耗组.add(项.次数组);
            }
            if (项.次数 !== null && 项.次数 !== undefined) 项.次数--;
            const 来源 = [...状态.队伍, ...状态.敌人].find(角色 => 角色.编号 === 项.来源);
            if (!来源 || 来源.生命 <= 0) continue;
            const 类别 = 项.效果方式 === 枚举.追加 && [枚举.普攻, 枚举.必杀].includes(状态.当前动作类别) ? (状态.当前动作类别 === 枚举.普攻 ? 枚举.普攻追加 : 枚举.必杀追加) : 枚举.触发;
            执行效果列(状态, 单位, 项.效果, 类别);
        }
    } finally { 状态.角色触发深度--; }
}

function 检查效果判定(状态, 来源, 判定 = []) {
    return 判定.every(条件 => {
        switch (条件.类型) {
            case 枚举.任一条件: return 条件.条件.some(子 => 检查效果判定(状态, 来源, [子]));
            case 枚举.全部条件: return 检查效果判定(状态, 来源, 条件.条件);
            case 枚举.自身职业: return 条件.职业.includes(来源.职业);
            case 枚举.角色存在: return 状态.队伍.some(单位 => (!条件.存活 || 单位.生命 > 0) && (条件.编号 ? 单位.编号 === 条件.编号 : 获取真实角色(单位.编号).全名.replace(/\s/g, '') === 条件.名称.replace(/\s/g, '')));
        }
        const 对象 = [枚举.层数, 枚举.生命比例].includes(条件.类型) ? 选目标(状态, 来源, 条件.目标 || '自身')[0] : null;
        let 数值;
        switch (条件.类型) {
            case 枚举.层数: 数值 = 对象?.计数?.[条件.键] || 0; break;
            case 枚举.生命比例: 数值 = 对象 ? 对象.生命 / 对象.生命上限 : 0; break;
            case 枚举.队伍属性: 数值 = 状态.队伍.filter(单位 => 单位.属性 === 条件.属性).length; break;
            case 枚举.队伍人数: 数值 = 状态.队伍.filter(单位 => (!条件.属性 || 单位.属性 === 条件.属性) && (!条件.职业 || 单位.职业 === 条件.职业)).length; break;
            case 枚举.属性种类: 数值 = new Set(状态.队伍.map(单位 => 单位.属性)).size; break;
            case 枚举.职业种类: 数值 = new Set(状态.队伍.map(单位 => 单位.职业)).size; break;
            default: 数值 = NaN;
        }
        if (!Number.isFinite(数值)) throw new Error(`尚未实现的效果条件：${条件.类型}`);
        switch (条件.比较) {
            case 枚举.包含: return 条件.数值.includes(数值);
            case 枚举.等值: return 数值 === 条件.数值;
            case 枚举.至少: return 数值 >= 条件.数值;
            case 枚举.至多: return 数值 <= 条件.数值;
            case 枚举.大于: return 数值 > 条件.数值;
            case 枚举.小于: return 数值 < 条件.数值;
            default: throw new Error('未知效果比较符');
        }
    });
}

function 调整最大冷却(目标, 变化) {
    if (目标.AI状态) {
        目标.AI状态.未裁剪最大冷却 = (目标.AI状态.未裁剪最大冷却 ?? 目标.AI状态.最大冷却) + 变化;
        目标.AI状态.最大冷却 = Math.max(0, 目标.AI状态.未裁剪最大冷却);
        目标.AI状态.当前冷却 = Math.min(目标.AI状态.当前冷却, 目标.AI状态.最大冷却);
    } else {
        目标.未裁剪最大冷却 = (目标.未裁剪最大冷却 ?? 目标.冷却) + 变化;
        目标.冷却 = Math.max(0, 目标.未裁剪最大冷却);
        目标.冷却剩余 = Math.min(目标.冷却剩余, 目标.冷却);
    }
}

function 刷新条件增益(状态) {
    for (const 来源 of 状态.队伍) for (const 效果 of 来源.动态增益 || []) {
        const 生效 = 来源.生命 > 0 && (效果.剩余 ?? 9999) > 0 && 检查效果判定(状态, 来源, 效果.判定);
        if (效果.类型 === 枚举.最大冷却变化) {
            效果.生效映射 ??= {};
            const 目标 = new Set(生效 ? 选目标(状态, 来源, 效果.目标) : []);
            for (const 对象 of [...状态.队伍, ...状态.敌人]) {
                const 数值 = 目标.has(对象) && !来源被免疫(对象, 效果) ? 档位(效果.数值, 来源) : 0;
                const 变化 = 数值 - (效果.生效映射[对象.编号] || 0);
                if (变化) 调整最大冷却(对象, 变化);
                效果.生效映射[对象.编号] = 数值;
            }
            continue;
        }
        for (const 对象 of [...状态.队伍, ...状态.敌人]) 对象.效果 = 对象.效果.filter(项 => 项.名称 !== 效果.名称 || 项.来源 !== 来源.编号);
        if (!生效) continue;
        for (const 目标 of 选目标(状态, 来源, 效果.目标)) {
            const 属性 = 效果.属性 === 枚举.受到伤害 && 状态.队伍.includes(目标) ? 枚举.受伤变化 : 效果.属性;
            添加增益(目标, 属性, 档位(效果.数值, 来源), 效果.剩余 ?? 9999, 来源, 效果.名称, 效果.层数 || 1, 效果.来源技能);
        }
    }
    for (const 来源 of 状态.队伍) 来源.动态增益 = (来源.动态增益 || []).filter(效果 => (效果.剩余 ?? 9999) > 0);
}

function 执行治疗(状态, 来源, 目标, 基础, 持续型 = false, 触发治疗 = false, 真实 = false, 技能增幅 = 0) {
    if (目标.生命 <= 0 || !(基础 >= 0)) return;
    const 施疗增幅 = 加成(来源, 持续型 ? 枚举.持续增幅 : 枚举.治疗增幅);
    // 施疗增幅与目标受疗属于同一次治疗计算，不能先把基础治疗向下取整再乘减疗；后者会在450257.325处错误丢掉1点。治疗量走 BattleCalculator 内核：真疗=⌊值×倍率⌋，普疗乘治疗/被治疗/治疗其他等乘区后一次向下取整并钳 ≥0。减疗来自目标自身受疗增加buff（如颠倒镜开场22839的−600%，内核钳≥−100%），不再有独立关卡旋钮。
    // 技能增幅（普攻伤害/必杀伤害）归"治疗其他"乘区而非施疗增幅：GetHealValue@0x800218a24c 把首参kind经 w2 传给 GetHealOtherBonusRate@0x800218d8f8，后者按kind加与伤害侧 GetOtherBonusRate@0x800218caec 完全相同的槽位（kind1→加成累计+0x230普攻伤害、kind2→+0x410与+0x290、kind5→+0x470与+0x290，末尾同调 GetKindEffRate@0x800218e054），独立于 GetHealBonusRate@0x800218a1fc 的+0x380施疗槽——两区各自(1+和)相乘，不能合并进同一因子。
    const 理论 = 计算治疗值({
        基础值: 基础, 倍率: 1, 变化率: 0,
        施槽: { 治疗加成: 施疗增幅 },
        受槽: { 被治疗加成: 加成(目标, 枚举.受疗增加), 持续被治疗加成: 加成(目标, 枚举.持续受疗增加), 治疗其他加成: { 1: 技能增幅 } },
        类别: 1, 真实, 持续型,
    });
    const 算出 = 理论;
    const 有效 = Math.min(目标.生命上限 - 目标.生命, 算出);
    目标.生命 += 有效;
    状态.本回合.理论回复 += 理论;
    状态.本回合.回复 += 有效;
    状态.本回合.溢出回复 += Math.max(0, 算出 - 有效);
    来源.统计.理论回复 += 理论;
    来源.统计.回复 += 有效;
    记录(状态, 枚举.治疗, `${来源.名称} → ${目标.名称}${持续型 ? ' · 持续' : ''}${算出 === 0 ? ' · 受疗压制' : ''}`, 算出, 目标.位置, 来源);
    刷新条件增益(状态);
    // 零回复也派发被治疗触发（实测定案：受疗压制到0时触发技仍发动）。
    被治疗触发(状态, 目标, 触发治疗, 持续型);
}

