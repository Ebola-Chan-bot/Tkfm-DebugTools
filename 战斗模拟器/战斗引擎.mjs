function 我方承伤(状态, 目标, 数值, 真实 = false, 名称 = '敌方伤害') {
    if (目标.生命 <= 0) return;
    const 回合增伤 = 状态.配置.颠倒规则 ? Math.min(50, 状态.回合 - 1) * .01 : 0;
    const 防御比例 = Math.max(0, Math.min(1, 状态.配置.防御减伤 + 加成(目标, '防御减伤') + (目标.编号 === 10006 ? .10 : 0)));
    let 伤害 = Math.max(0, Math.floor(数值 * (真实 ? 1 : Math.max(0, 1 + 回合增伤 + 加成(目标, '受伤变化')) * (目标.防御 ? 1 - 防御比例 : 1))));
    let 吸收 = 0;
    for (const 护盾 of 目标.护盾) {
        const 本层吸收 = Math.min(护盾.数值, 伤害);
        护盾.数值 -= 本层吸收;
        伤害 -= 本层吸收;
        吸收 += 本层吸收;
    }
    目标.护盾 = 目标.护盾.filter(层 => 层.数值 > 0);
    const 有效 = Math.min(目标.生命, 伤害);
    目标.生命 -= 有效;
    目标.统计.承伤 += 有效;
    目标.统计.护盾吸收 += 吸收;
    状态.本回合.承伤 += 有效;
    状态.本回合.护盾吸收 += 吸收;
    记录(状态, '承伤', `${目标.名称} · ${名称}${真实 ? ' · 真实' : ''}`, 有效, 目标.位置);
    if (目标.生命 === 0) 记录(状态, '倒下', `${目标.名称}无法继续战斗`, null, 目标.位置);
}

