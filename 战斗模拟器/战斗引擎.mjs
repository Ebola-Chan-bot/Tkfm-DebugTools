function 自动事件(状态, 时点) {
    if (!状态.配置.自动敌方 || 状态.AI扫描中 || !状态.敌人.every(单位 => 单位.AI状态)) return;
    状态.AI扫描中 = true;
    try {
        for (const 单位 of 状态.敌人.filter(项 => 项.生命 > 0)) {
            const 运行 = 单位.AI状态;
            for (const 规则 of 敌方规则[运行.阶段编号 || 单位.编号]) {
                if (规则.动作码 === 1) continue;
                const 开场规则 = 规则.条件.some(项 => 项.编号 === 74);
                if (开场规则 !== (时点 === 枚举.开场)) continue;
                if (!开场规则 && 规则.触发模式 === 1) continue;
                const 键 = String(规则.槽位);
                const 匹配 = 匹配敌方规则(规则, { 状态, 单位, 时点 });
                const 上次 = 运行.条件状态[键] || false;
                运行.条件状态[键] = 匹配;
                if (!匹配 || 运行.已执行.includes(键) || (规则.触发模式 === 2 && 上次)) continue;
                if (规则.触发模式 === 0 || 开场规则) 运行.已执行.push(键);
                // 血线在我方结算期间只登记，不立即执行；进入该敌人的敌方回合后再结算并顶替原本行动。
                if (是血线阶段规则(规则)) {
                    运行.待触发血线 = structuredClone(规则);
                    continue;
                }
                执行AI技能(状态, 单位, 规则, 时点);
                if (!开场规则 && (规则.动作码 === 4 || 规则.行为标志 === 1)) 运行.本回合行动 = true;
                if (状态.队伍.every(项 => 项.生命 <= 0) || 状态.敌人.every(项 => 项.生命 <= 0)) return;
                if (规则.行为标志 === 1) break;
            }
        }
    } finally { delete 状态.AI扫描中; }
}

function 自动敌方回合(状态) {
    if (状态.阶段 !== 枚举.敌方) throw new Error('我方仍有角色尚未行动');
    if (!状态.敌人.every(单位 => 单位.AI状态)) throw new Error('该存档未启用自动 AI，请应用当前关卡模型后重新开始');
    // 每回合加攻按原包监听执行：爱你39025与颠倒镜周期技能均由数据提供，不再写死5%。
    if (状态.配置.关卡 !== 60155) for (const 单位 of 状态.敌人.filter(单位 => 单位.生命 > 0)) 派发原包触发(状态, 单位, 枚举.每回合);
    自动事件(状态, 枚举.敌方行动前);
    for (const 单位 of 状态.敌人.filter(项 => 项.生命 > 0)) {
        if (状态.队伍.every(项 => 项.生命 <= 0)) break;
        const 运行 = 单位.AI状态;
        if (运行.待触发血线) {
            const 规则 = 运行.待触发血线;
            运行.待触发血线 = null;
            执行AI技能(状态, 单位, 规则, 枚举.敌方回合);
            运行.本回合行动 = true;
            单位.已行动 = true;
            continue;
        }
        if ([枚举.睡眠, 枚举.麻痹, 枚举.封印].some(属性 => 加成(单位, 属性) > 0)) {
            运行.本回合行动 = true;
            单位.已行动 = true;
            标记日志归属(状态, 枚举.敌方);
            记录(状态, 枚举.AI, `${单位.名称}受控，跳过行动`);
            continue;
        }
        if (单位.蓄力) {
            const 持续 = 单位.蓄力.持续 ?? 1;
            if (状态.回合 - 单位.蓄力.开始回合 >= 持续) {
                const 解除技能 = 单位.蓄力.原包技能;
                单位.蓄力 = null;
                执行原包技能(状态, 单位, 解除技能, { 动作类别: 枚举.触发 });
            } else 记录(状态, 枚举.AI, `${单位.名称}继续蓄力`);
            运行.本回合行动 = true;
        }
        if (运行.本回合行动) continue;
        let 已行动 = false;
        // 回合行动按 TActDetermine 槽位顺序逐行判定，行为标志(patternPara3)=1 才终止本组后续行；动作码本身不终止。旧实现按行为标志降序排序+动作码1即break，把爱你子AI(52541/52545)末位的普攻(行为标志1)提到潜行(行为标志0)之前并提前终止，致T2只普攻不潜行（实测先潜行1243849再普攻621924）。槽位序+仅行为标志终止同时兼容颠倒镜43248（周期技能行为标志1在普攻前，先匹配先终止）。
        const 回合规则 = 敌方规则[运行.阶段编号 || 单位.编号].filter(项 => 项.触发模式 === 1 || (项.动作码 === 1 && 项.触发模式 === 0));
        for (const 规则 of 回合规则) {
            if (加成(单位, 枚举.沉默) > 0 && 规则.技能编号 > 0 && 规则.动作码 === 4) continue;
            if (!匹配敌方规则(规则, { 状态, 单位, 时点: 枚举.敌方回合 })) continue;
            执行AI技能(状态, 单位, 规则, 枚举.敌方回合);
            已行动 = true;
            if (规则.行为标志 === 1) break;
            if (状态.队伍.every(项 => 项.生命 <= 0)) break;
        }
        if (!已行动) 记录(状态, 枚举.AI, `${单位.名称}待机`);
        单位.已行动 = true;
    }
    const 技能 = 状态.AI轨迹.filter(项 => 项.回合 === 状态.回合 && 项.时点 !== 枚举.开场).map(项 => `${状态.敌人.find(单位 => 单位.编号 === 项.单位编号).名称}:${项.技能编号 ? (原包关卡机制.技能[项.技能编号]?.名称 ?? '#' + 项.技能编号) : '普攻'}`).join(' / ');
    const 首领回血 = 状态.配置.关卡 === 60155 && (状态.首领.原包触发 || []).some(项 => 项.来源技能 === 28777 && 项.剩余 > 0) ? 1 : 0;
    结束敌方回合(状态, 技能 || '待机', 首领回血);
}

export function 预览敌方行动(状态) {
    return 状态.敌人.filter(单位 => 单位.生命 > 0).map(单位 => {
        if (!单位.AI状态) return { 名称: 单位.名称, 行动: '旧手动存档', 冷却: null };
        if (单位.AI状态.待触发血线) return { 名称: 单位.名称, 行动: 原包关卡机制.技能[单位.AI状态.待触发血线.技能编号]?.名称 ?? String(单位.AI状态.待触发血线.技能编号), 技能: [单位.AI状态.待触发血线.技能编号], 冷却: 单位.AI状态.当前冷却 };
        if (单位.蓄力) return { 名称: 单位.名称, 行动: '蓄力中', 冷却: 单位.AI状态.当前冷却 };
        const 规则 = 敌方规则[单位.AI状态.阶段编号 || 单位.编号].filter(项 => 项.触发模式 === 1 || (项.动作码 === 1 && 项.触发模式 === 0));
        const 命中 = [];
        for (const 项 of 规则) {
            if (!匹配敌方规则(项, { 状态, 单位, 时点: 枚举.敌方回合 })) continue;
            命中.push(项.动作码 === 1 ? 枚举.普攻 : 项.技能编号);
            if (项.行为标志 === 1) break;
        }
        return { 名称: 单位.名称, 行动: 命中.length ? 命中.map(编号 => 编号 === 枚举.普攻 ? '普攻' : (原包关卡机制.技能[编号]?.名称 ?? '#' + 编号)).join(' + ') : '待机', 技能: 命中, 冷却: 单位.AI状态.当前冷却 };
    });
}

function 结束敌方回合(状态, 技能, 首领回血比例 = 0) {
    // 敌方行动全部结束后才进入敌方回合末；我方续疗已在更早的我方回合末结算，不能在这里重复或延后。
    结算回合末(状态, 枚举.敌方, 首领回血比例);
    状态.回合报表.push({ 回合: 状态.回合, ...状态.本回合, 首领生命: 状态.首领.生命, 生命: 状态.队伍.map(单位 => 单位.生命), 存活: 状态.队伍.filter(单位 => 单位.生命 > 0).length, 技能 });
    if (状态.队伍.every(单位 => 单位.生命 <= 0) || 状态.敌人.every(敌人 => 敌人.生命 <= 0) || 状态.回合 >= 回合上限) {
        状态.阶段 = 枚举.结束;
        return;
    }
    状态.回合++;
    状态.阶段 = 枚举.我方;
    状态.本回合 = 空统计();
    状态.我方动作计数 = { 普攻: 0, 必杀: 0, 防御: 0 };
    状态.敌方行动记录 = [];
    for (const 单位 of [...状态.队伍, ...状态.敌人]) {
        const 暂停冷却 = 加成(单位, 枚举.冷却暂停) > 0;
        单位.来源免疫 = (单位.来源免疫 || []).filter(项 => --项.剩余 > 0);
        单位.状态标记 = (单位.状态标记 || []).filter(项 => --项.剩余 > 0);
        单位.最大冷却状态 = (单位.最大冷却状态 || []).filter(项 => {
            if (--项.剩余 > 0) return true;
            调整最大冷却(单位, -项.数值);
            return false;
        });
        // 敌方回合结束只扣我方阶段施加的效果；敌方阶段施加的减益不归这个时点管，其扣减在下一个我方回合结束（检查我方回合结束）。
        扣减效果(单位, false);
        单位.触发 = (单位.触发 || []).filter(效果 => --效果.剩余 > 0 && 效果.次数 !== 0);
        单位.原包触发 = (单位.原包触发 || []).filter(效果 => --效果.剩余 > 0);
        单位.护盾 = 单位.护盾.filter(效果 => --效果.剩余 > 0);
        单位.续疗 = 单位.续疗.filter(效果 => --效果.剩余 > 0);
        for (const 效果 of 单位.动态增益 || []) 效果.剩余--;
        if (状态.敌人.includes(单位)) {
            单位.已行动 = false;
            单位.防御 = false;
            if (单位.AI状态) {
                if (!暂停冷却) 单位.AI状态.当前冷却 = Math.max(0, 单位.AI状态.当前冷却 - 1);
                单位.AI状态.本回合行动 = false;
            } else if (!暂停冷却) 单位.冷却剩余 = Math.max(0, 单位.冷却剩余 - 1);
            continue;
        }
        单位.已行动 = false;
        单位.防御 = false;
        if (!暂停冷却) 单位.冷却剩余 = Math.max(0, 单位.冷却剩余 - 1);
    }
    刷新条件增益(状态);
    for (const 单位 of 状态.队伍.filter(项 => 项.生命 > 0)) 执行效果列(状态, 单位, 单位.回合开始 || [], 枚举.回合开始);
    for (const 单位 of 状态.队伍.filter(项 => 项.生命 > 0)) 派发角色触发(状态, 单位, 枚举.回合开始);
    const 队长 = 状态.队伍[0];
    自动事件(状态, 枚举.回合开始);
    检查我方回合结束(状态);
}

export function 结算操作(原状态, 操作) {
    const 状态 = structuredClone(原状态);
    当前状态 = 状态;
    状态.当前手动分支 = 操作.手动分支;
    delete 状态.手动分支序;
    delete 状态.本操作有随机分支;
    if (Number.isInteger(操作.随机)) 状态.随机状态 = 操作.随机 >>> 0;
    if (状态.阶段 === 枚举.结束) throw new Error('战斗已经结束');
    // 敌方行动由 EnemyAI 全自动驱动（随机目标分支经手动分支/随机种子控制），不接受手动敌方技能、机制或校准操作。
    if (操作.类型 !== 枚举.角色) throw new Error('未知操作类型');
    角色行动(状态, 操作);
    return 状态;
}

export function 重放战斗(配置, 操作列表) {
    return 操作列表.reduce((状态, 操作) => 结算操作(状态, 操作), 新建战斗(配置));
}