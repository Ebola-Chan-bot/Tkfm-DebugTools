function 有限正数(数值, 名称) {
    if (!Number.isFinite(数值) || 数值 <= 0) throw new Error(`${名称}必须为正数`);
    return 数值;
}

function 档位(数值, 单位) {
    return Array.isArray(数值) ? 数值[单位.羁绊 - 1] : 数值;
}

function 专属编号(单位) {
    return 单位.技能来源 === '专属模型' ? 单位.编号 : 0;
}

function 属性倍率(来源, 目标) {
    if (!来源.属性 || !目标.属性) return 1;
    const 克制 = { 火: '风', 风: '水', 水: '火', 光: '暗', 暗: '光' };
    const 修正 = 克制[来源.属性] === 目标.属性 ? .5 : ['火', '水', '风'].includes(来源.属性) && 克制[目标.属性] === 来源.属性 ? -.25 : 0;
    return 1 + 修正 * Math.max(0, 1 + 加成(来源, '相克抵消'));
}

function 按动作批次(状态, 执行, 动作类别 = '触发') {
    const 上一批次 = 状态.当前伤害批次 ?? null;
    const 上一类别 = 状态.当前动作类别 ?? null;
    状态.动作批次序 = (状态.动作批次序 || 0) + 1;
    状态.当前伤害批次 = 状态.动作批次序;
    状态.当前动作类别 = 动作类别;
    try { return 执行(); }
    finally { 状态.当前伤害批次 = 上一批次; 状态.当前动作类别 = 上一类别; }
}

function 派发受击(状态, 目标, 类别) {
    const 批次 = 状态.当前伤害批次;
    if (批次 !== null && 批次 !== undefined && 目标.最近受击批次 === 批次) return;
    if (批次 !== null && 批次 !== undefined) 目标.最近受击批次 = 批次;
    派发角色触发(状态, 目标, '被攻击');
    if (类别 === '普攻') 派发角色触发(状态, 目标, '被普攻');
    目标.效果 = 目标.效果.filter(项 => 项.受击限次 === undefined || --项.受击限次 > 0);
}

