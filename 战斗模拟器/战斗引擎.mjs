function 有限正数(数值, 名称) {
    if (!Number.isFinite(数值) || 数值 <= 0) throw new Error(`${名称}必须为正数`);
    return 数值;
}

function 档位(数值, 单位) {
    return Array.isArray(数值) ? 数值[单位.羁绊 - 1] : 数值;
}

function 空统计() {
    return { 伤害: 0, 回复: 0, 理论回复: 0, 溢出回复: 0, 护盾生成: 0, 理论护盾: 0, 护盾吸收: 0, 承伤: 0, 首领回血: 0 };
}

function 记录(状态, 类别, 内容, 数值 = null, 目标 = null) {
    状态.日志.push({ 回合: 状态.回合, 类别, 内容, 数值, 目标 });
}

function 选目标(状态, 来源, 选择 = '全体') {
    const 活人 = 状态.队伍.filter(单位 => 单位.生命 > 0);
    if (选择 === '首领') return [状态.敌人[状态.攻击目标]];
    if (选择 === '敌方全体') return 状态.敌人.filter(单位 => 单位.生命 > 0);
    if (选择 === '自身') return [来源];
    if (选择 === '其他') return 活人.filter(单位 => 单位.编号 !== 来源.编号);
    if (选择 === '最低') return [最低生命目标(状态.队伍)].filter(Boolean);
    if (选择 === '首位') return 活人.filter(单位 => 单位.位置 === 0);
    if (选择 === '末位') return 活人.filter(单位 => 单位.位置 === 4);
    if (选择 === '攻击妨碍') return 活人.filter(单位 => ['攻击者', '妨碍者'].includes(单位.职业));
    if (选择 === '攻击治疗') return 活人.filter(单位 => ['攻击者', '治疗者'].includes(单位.职业));
    const 职业 = { 攻击: '攻击者', 治疗: '治疗者', 辅助: '辅助者', 守护: '守护者' }[选择];
    if (职业) return 活人.filter(单位 => 单位.职业 === 职业);
    if (['火', '水', '风', '光', '暗'].includes(选择)) return 活人.filter(单位 => 单位.属性 === 选择);
    if (选择 !== '全体') throw new Error(`尚未实现的效果目标：${选择}`);
    return 活人;
}

export function 加成(单位, 属性) {
    const 固定 = (单位.效果 || []).filter(效果 => 效果.属性 === 属性).reduce((合计, 效果) => 合计 + 效果.数值 * 效果.层数, 0);
    if (属性 === '攻击比例' && 单位.幸运物 >= 1) return 固定 + .30;
    if (属性 === '受疗增加' && 单位.幸运物 >= 2) return 固定 + .30;
    if (属性 === '普攻伤害' && 单位.幸运物 >= 3) return 固定 + .50;
    return 固定;
}

export function 当前攻击(单位) {
    return Math.max(0, Math.floor(单位.攻击 * Math.max(0, 1 + 加成(单位, '攻击比例')) + 加成(单位, '攻击固定')));
}

export function 当前护盾(单位) {
    return (单位.护盾 || []).reduce((合计, 层) => 合计 + 层.数值, 0);
}

function 添加增益(目标, 属性, 数值, 持续, 来源, 名称, 上限 = 1) {
    if (!Number.isFinite(数值) || !Number.isInteger(持续) || 持续 < 1) throw new Error(`效果参数不合法：${名称}`);
    const 已有 = 目标.效果.find(效果 => 效果.名称 === 名称 && 效果.来源 === 来源.编号 && 效果.属性 === 属性);
    if (已有) {
        已有.数值 = 数值;
        已有.剩余 = 持续;
        已有.层数 = Math.min(上限, 已有.层数 + 1);
    } else 目标.效果.push({ 属性, 数值, 剩余: 持续, 来源: 来源.编号, 名称, 层数: 1 });
}

function 生命初始化增益(单位) {
    单位.生命上限 = Math.floor(单位.生命上限 * Math.max(.01, 1 + 加成(单位, '生命比例')));
    单位.生命 = 单位.生命上限;
}

export function 新建战斗(配置) {
    const 夏日 = 当前关卡(配置).编号 === '夏日尾声';
    if (配置.自动敌方) 校验AI配置(配置);
    if (配置.自动敌方 && (!Number.isInteger(配置.AI初始冷却 ?? 1) || (配置.AI初始冷却 ?? 1) < 0 || (配置.AI初始冷却 ?? 1) > 100)) throw new Error('AI 初始冷却须为 0 至 100');
    if (夏日 && 配置.颠倒规则) throw new Error('夏日尾声不能启用颠倒镜规则');
    if (!Array.isArray(配置.队伍) || 配置.队伍.length !== 5) throw new Error('请选择五位角色');
    if (new Set(配置.队伍.map(单位 => 单位.编号)).size !== 5) throw new Error('队伍中不能有重复角色');
    for (const [名称, 下限, 上限] of [['首领减伤', 0, 2], ['防御减伤', 0, 1], ['受疗降低', 0, 10], ['受盾降低', 0, 10]]) {
        if (!Number.isFinite(配置[名称]) || 配置[名称] < 下限 || 配置[名称] > 上限) throw new Error(`${名称}超出范围`);
    }
    if (!Number.isInteger(配置.回合上限) || 配置.回合上限 < 1 || 配置.回合上限 > 100) throw new Error('回合上限须为 1 至 100');
    const 队伍 = 配置.队伍.map((单位, 位置) => {
        if (!Number.isInteger(单位.羁绊) || 单位.羁绊 < 1 || 单位.羁绊 > 5) throw new Error('羁绊须为 1 至 5');
        if (!Number.isInteger(单位.冷却) || 单位.冷却 < 1 || 单位.冷却 > 50) throw new Error('必杀冷却须为 1 至 50');
        if (!['攻击者', '治疗者', '守护者', '辅助者', '妨碍者'].includes(单位.职业)) throw new Error('未知角色职业');
        return { ...structuredClone(单位), 防御技能: structuredClone(单位.防御 || []), 位置, 生命上限: 有限正数(单位.生命上限, '角色生命'), 生命: 单位.生命上限, 攻击: 有限正数(单位.攻击, '角色攻击'), 已行动: false, 防御: false, 冷却剩余: 0, 效果: [], 护盾: [], 续疗: [], 计数: {}, 统计: 空统计(), 幸运物: 0 };
    });
    if (夏日 && (!Array.isArray(配置.敌人) || 配置.敌人.length !== 5 || 配置.敌人.some((单位, 位置) => 单位.编号 !== 夏日敌人[位置].编号))) throw new Error('夏日尾声须配置五名正确的敌人');
    const 敌人 = 夏日 ? 配置.敌人.map((单位, 位置) => ({
        ...structuredClone(单位), 位置, 名称: 夏日敌人[位置].名称,
        生命上限: 有限正数(单位.生命上限, '敌方生命'), 生命: 单位.生命上限,
        攻击: 有限正数(单位.攻击, '敌方攻击'), 效果: [], 已行动: false, 蓄力: null,
        夏日层数: 0, 夏日攻击层数: 0, 每回合回血: 位置 === 0,
    })) : [{ 编号: 配置.首领编号 ?? 43248, 名称: 配置.首领名称 ?? '颠倒镜', 生命上限: 有限正数(配置.首领生命, '首领生命'), 生命: 配置.首领生命, 攻击: 有限正数(配置.首领攻击, '首领攻击'), 效果: [], 蓄力: null, 重力易伤: false }];
    const 状态 = {
        配置: structuredClone(配置),
        回合: 1,
        阶段: '我方',
        队伍,
        首领: 敌人[0], 敌人, 攻击目标: 0, 敌方行动记录: [],
        累计伤害: 0,
        日志: [],
        回合报表: [],
        本回合: 空统计(),
        治疗事件深度: 0,
        我方动作计数: { 普攻: 0, 必杀: 0, 防御: 0 }, AI轨迹: [],
    };
    for (const 单位 of 队伍) {
        执行效果列(状态, 单位, 单位.初始 || [], '初始');
        if (单位.编号 === 10006 && 单位.解放 === 2) 执行效果列(状态, 单位, 单位.解放初始 || [], '解放初始');
    }
    const 队长 = 队伍[0];
    const 领队效果 = 队长.编号 === 10006 && 队长.解放 === 2 ? 队长.解放队长 : 队长.队长;
    执行效果列(状态, 队长, 领队效果 || [], '队长');
    for (const 单位 of 队伍) {
        生命初始化增益(单位);
        if (单位.编号 === 10006) 单位.冷却 = 单位.解放 ? (单位.羁绊 >= 3 ? 4 : 5) : (单位.羁绊 === 5 ? 4 : 5);
        if (单位.编号 === 10053) 单位.冷却 = 单位.羁绊 >= 3 ? 4 : 5;
    }
    if (队长.编号 === 10133 && 队伍.filter(单位 => 单位.职业 === '辅助者').length >= 2) 添加增益(队长, '受盾变化', -6, 9999, 队长, '奈奈美队长受盾限制');
    状态.日志 = [];
    if (配置.自动敌方) {
        for (const 单位 of 敌人) {
            const 基础冷却 = 敌方基础冷却[单位.编号];
            if (!基础冷却) throw new Error(`尚未录入该敌人的 AI：${单位.编号}`);
            const 被动冷却 = 夏日 && 单位.位置 === 0 && (配置.敌方星等 ?? 4) >= 5 ? 10 : 0;
            单位.AI状态 = { 最大冷却: 基础冷却 + 被动冷却, 当前冷却: 配置.AI初始冷却 ?? 1, 已执行: [], 条件状态: {}, 本回合行动: false };
        }
        自动事件(状态, '开场');
    } else if (夏日) {
        if (![0, 28759, 28760].includes(配置.夏日开场)) throw new Error('未知夏日开场方案');
        if (配置.夏日开场) 夏日机制结算(状态, { 技能: 配置.夏日开场 === 28759 ? '寻找泳装-95%' : '寻找泳装-125%' });
    }
    记录(状态, '系统', 配置.自动敌方 ? '敌方按原始 AI 规则自动行动；条件命中记录可回放核查' : '采用手动 Boss 行动；面板、公式及未解条件以模型设置为准');
    return 状态;
}

export function 最低生命目标(队伍, 按上限 = false) {
    const 存活 = 队伍.filter(单位 => 单位.生命 > 0);
    return 存活.reduce((最低, 单位) => {
        const 左 = 按上限 ? 单位.生命上限 : 单位.生命 / 单位.生命上限;
        const 右 = 最低 ? (按上限 ? 最低.生命上限 : 最低.生命 / 最低.生命上限) : Infinity;
        return 左 < 右 ? 单位 : 最低;
    }, null);
}

export function 可选敌人(状态) {
    const 存活 = 状态.敌人.filter(单位 => 单位.生命 > 0);
    const 嘲讽 = 存活.filter(单位 => 加成(单位, '嘲讽') > 0);
    return 嘲讽.length ? 嘲讽 : 存活;
}

function 敌方承伤(状态, 目标, 数值) {
    const 最低 = 加成(目标, '锁血') > 0 ? Math.max(1, Math.ceil(目标.生命上限 * .0001)) : 0;
    const 有效 = Math.min(Math.max(0, 目标.生命 - 最低), Math.max(0, Math.floor(数值)));
    目标.生命 -= 有效;
    if (目标.生命 === 0) 记录(状态, '倒下', `${目标.名称}被击破`, null, 目标.名称);
    if (状态.配置.自动敌方 && 状态.配置.AI事件时点 !== '行动后') 自动事件(状态, '伤害后');
    return 有效;
}

function 造成伤害(状态, 来源, 倍率, 类别, 名称, 目标 = 状态.敌人[状态.攻击目标]) {
    if (!(倍率 > 0)) return;
    if (!目标 || 目标.生命 <= 0) return;
    const 规则 = 状态.配置.颠倒规则;
    const 受益职业 = ['治疗者', '辅助者'].includes(来源.职业);
    const 职业造成 = 规则 ? (受益职业 ? 1 : -6) : 0;
    const 职业易伤 = 规则 && 受益职业 ? 1 : 0;
    const 技能增幅 = 加成(来源, 类别 === '普攻' ? '普攻伤害' : '必杀伤害');
    const 触发增幅 = 类别 === '触发' ? 加成(来源, '触发增幅') : 0;
    const 属性增幅 = 来源.属性 === '风' ? 加成(目标, '风易伤') : 来源.属性 === '水' || 来源.属性 === '光' ? 加成(目标, '水光易伤') : 0;
    const 防御倍率 = 加成(目标, '防御') > 0 ? 1 - 状态.配置.防御减伤 : 1;
    const 乘区 = [1 + 职业造成 + 加成(来源, '造成伤害'), 1 + (类别 === '触发' ? 触发增幅 : 技能增幅), 1 - 状态.配置.首领减伤 + 职业易伤 + 加成(目标, '受到伤害'), 1 + 属性增幅, 防御倍率];
    const 数值 = Math.max(0, Math.floor(当前攻击(来源) * 倍率 * 乘区.reduce((积, 项) => 积 * Math.max(0, 项), 1)));
    const 有效 = 敌方承伤(状态, 目标, 数值);
    状态.累计伤害 += 有效;
    状态.本回合.伤害 += 有效;
    来源.统计.伤害 += 有效;
    if (状态.配置.关卡 !== '夏日尾声' && 状态.首领.蓄力) {
        状态.首领.蓄力.命中++;
        if (状态.首领.蓄力.命中 >= 99) {
            状态.首领.蓄力 = null;
            记录(状态, '机制', '蓄力解除（计数按伤害段估计，可手动校准）');
        }
    }
    记录(状态, '伤害', `${来源.名称} → ${目标.名称} · ${名称}`, 有效, 目标.名称);
}

function 被治疗触发(状态, 目标, 触发治疗) {
    if (状态.治疗事件深度 >= 8) throw new Error('治疗触发深度超出模型限制');
    状态.治疗事件深度++;
    const 队长 = 状态.队伍[0];
    if (队长.编号 === 10190) {
        目标.计数.守护 = Math.min(40, (目标.计数.守护 || 0) + 1);
        添加增益(目标, '触发增幅', .0225, 9999, 队长, '守护众人', 40);
    }
    const 花魁 = 状态.队伍.find(单位 => 单位.编号 === 10085 && 单位.生命 > 0);
    if (花魁 && !触发治疗) {
        添加增益(目标, '攻击比例', .125, 2, 花魁, '花魁受疗加攻');
        添加增益(目标, '造成伤害', .05, 2, 花魁, '花魁受疗增伤');
        if (花魁.位置 === 0 && ['火', '暗'].includes(目标.属性)) {
            添加增益(目标, '必杀伤害', .075, 2, 花魁, '花魁队长受疗必杀');
            添加增益(目标, '普攻伤害', .10, 2, 花魁, '花魁队长受疗普攻');
        }
    }
    if (目标.编号 === 10190) {
        const 魔力 = 目标.计数.魔力 || 0;
        for (const 单位 of 状态.队伍.filter(项 => 项.生命 > 0)) {
            添加增益(单位, '触发增幅', .06, 9999, 目标, '凯萨的永眠', 10);
            添加增益(单位, '攻击追击', .30, 1, 目标, '凯萨的永眠追击');
            添加增益(单位, '造成伤害', .015, 9999, 目标, '信守约定', 10);
            if (魔力 >= 1 && ['水', '光'].includes(单位.属性)) 添加增益(单位, '造成伤害', .10, 1, 目标, '魔力丧失');
            if (魔力 === 3 && 单位.编号 !== 目标.编号) 添加增益(单位, '攻击固定', 当前攻击(目标) * .06, 1, 目标, '魔力丧失加攻');
        }
        记录(状态, '触发', '丧巴被治疗：永眠与信守约定叠层', null, 目标.位置);
    }
    状态.治疗事件深度--;
}

function 执行治疗(状态, 来源, 目标, 基础, 持续型 = false, 触发治疗 = false) {
    if (目标.生命 <= 0 || !(基础 >= 0)) return;
    const 施疗增幅 = 加成(来源, 持续型 ? '持续增幅' : '治疗增幅') + (来源.编号 === 10190 && 来源.计数.魔力 >= 2 ? .50 : 0);
    const 理论 = Math.max(0, Math.floor(基础 * Math.max(0, 1 + 施疗增幅)));
    const 减少 = 状态.配置.颠倒规则 ? 状态.配置.受疗降低 : 0;
    const 算出 = Math.max(0, Math.floor(理论 * Math.max(0, 1 + 加成(目标, '受疗增加') - 减少)));
    const 有效 = Math.min(目标.生命上限 - 目标.生命, 算出);
    目标.生命 += 有效;
    状态.本回合.理论回复 += 理论;
    状态.本回合.回复 += 有效;
    状态.本回合.溢出回复 += Math.max(0, 算出 - 有效);
    来源.统计.理论回复 += 理论;
    来源.统计.回复 += 有效;
    记录(状态, '治疗', `${来源.名称} → ${目标.名称}${持续型 ? ' · 持续' : ''}${算出 === 0 ? ' · 受疗压制' : ''}`, 有效, 目标.位置);
    if (有效 > 0 || 状态.配置.零回复触发) 被治疗触发(状态, 目标, 触发治疗);
}

function 执行效果列(状态, 来源, 列表, 阶段名) {
    for (const [序号, 效果] of 列表.entries()) {
        if (效果.条件 === '四属性' && new Set(状态.队伍.map(单位 => 单位.属性)).size !== 4) continue;
        if (效果.条件 === '四风' && 状态.队伍.filter(单位 => 单位.属性 === '风').length < 4) continue;
        if (效果.条件 === '完全解放' && 来源.解放 !== 2) continue;
        if (效果.条件 === '部分解放' && 来源.解放 !== 1) continue;
        const 目标列表 = 选目标(状态, 来源, 效果.目标);
        const 数值 = 档位(效果.数值 ?? 效果.倍率 ?? 0, 来源);
        if (!Number.isFinite(数值)) throw new Error('技能档位数据缺失');
        const 持续 = 档位(效果.持续 ?? 9999, 来源);
        const 名称 = 效果.名称 || `${来源.编号}:${阶段名}:${序号}`;
        const 施放攻击 = 当前攻击(来源);
        if (效果.类型 === '伤害') {
            if (效果.目标 === '敌方全体') for (const 目标 of 目标列表) 造成伤害(状态, 来源, 数值, 阶段名, 名称, 目标);
            else 造成伤害(状态, 来源, 数值, 阶段名, 名称);
            continue;
        }
        for (const 目标 of 目标列表) {
            if (效果.类型 === '增益') {
                const 基准 = 效果.基准 === '当前攻击' ? 施放攻击 : 效果.基准 === '基础攻击' ? 来源.攻击 : 1;
                添加增益(目标, 效果.属性, 数值 * 基准, 持续, 来源, 名称, 效果.层数 || 1);
            } else if (效果.类型 === '治疗') 执行治疗(状态, 来源, 目标, 施放攻击 * 数值, false, 效果.触发治疗);
            else if (效果.类型 === '持续治疗') {
                const 续疗 = { 来源: 来源.编号, 基础: 施放攻击 * 数值, 剩余: 持续, 名称 };
                const 旧 = 目标.续疗.findIndex(项 => 项.名称 === 名称 && 项.来源 === 来源.编号);
                if (旧 >= 0) 目标.续疗[旧] = 续疗;
                else 目标.续疗.push(续疗);
            } else if (效果.类型 === '护盾') {
                const 基准 = 效果.基准 === '当前攻击' ? 施放攻击 : 效果.基准 === '目标生命' ? 目标.生命上限 : 来源.生命上限;
                const 理论 = Math.max(0, Math.floor(基准 * 数值 * Math.max(0, 1 + 加成(来源, '护盾增幅'))));
                const 压制 = 状态.配置.颠倒规则 ? 状态.配置.受盾降低 : 0;
                const 实际 = Math.max(0, Math.floor(理论 * Math.max(0, 1 + 加成(目标, '受盾变化') - 压制)));
                目标.护盾 = 目标.护盾.filter(层 => 层.名称 !== 名称 || 层.来源 !== 来源.编号);
                if (实际 > 0) 目标.护盾.push({ 数值: 实际, 剩余: 持续, 来源: 来源.编号, 名称 });
                来源.统计.护盾生成 += 实际;
                状态.本回合.护盾生成 += 实际;
                状态.本回合.理论护盾 += 理论;
                记录(状态, '护盾', `${来源.名称} → ${目标.名称}${实际 === 0 ? ' · 受盾压制' : ''}`, 实际, 目标.位置);
            } else if (效果.类型 === '解除防御') {
                if (状态.敌人.includes(目标) && 加成(目标, '防御') > 0) 解除敌方防御(状态, 目标);
            } else if (效果.类型 === '计数') {
                目标.计数[效果.键] = Math.min(效果.上限, (目标.计数[效果.键] || 0) + 1);
                if (效果.键 === '幸运物') 目标.幸运物 = 目标.计数.幸运物;
            } else throw new Error(`未支持的技能效果：${效果.类型}`);
        }
    }
}

