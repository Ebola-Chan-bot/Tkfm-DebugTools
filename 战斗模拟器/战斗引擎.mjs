function 选目标(状态, 来源, 选择 = 枚举.全体) {
    const 来源为敌方 = 状态.敌人.includes(来源);
    const 本方 = 来源为敌方 ? 状态.敌人 : 状态.队伍;
    const 对方 = 来源为敌方 ? 状态.队伍 : 状态.敌人;
    const 活人 = 本方.filter(单位 => 单位.生命 > 0);
    if (typeof 选择 === 'object' && 选择) {
        if (选择.任一) return [...new Set(选择.任一.flatMap(子 => 选目标(状态, 来源, 子)))];
        const 列表 = 选择.固定阵营 ? 选择.固定阵营 === 枚举.敌方 ? 状态.敌人 : 状态.队伍 : 选择.阵营 === 枚举.敌方 ? 对方 : 本方;
        const 匹配 = 列表.filter(单位 => 单位.生命 > 0 && (!选择.排除自身 || 单位.编号 !== 来源.编号) && (!选择.编号?.length || 选择.编号.includes(单位.编号)) && (!选择.属性?.length || 选择.属性.includes(单位.属性)) && (!选择.排除属性?.includes(单位.属性)) && (!选择.职业?.length || 选择.职业.includes(单位.职业)) && (!选择.排除职业?.includes(单位.职业)) && (!选择.站位?.length || 选择.站位.includes(单位.位置 + 1)));
        if (!选择.排序) return 匹配;
        const 值 = (({ [枚举.攻击]: 当前攻击, [枚举.生命比例]: 单位 => 单位.生命 / 单位.生命上限 })[选择.排序.字段] ?? (单位 => 单位[选择.排序.字段]));
        return 匹配.sort((甲, 乙) => (值(甲) - 值(乙)) * (选择.排序.升序 ? 1 : -1) || 甲.位置 - 乙.位置).slice(0, 选择.排序.数量 || 1);
    }
    if (/^站位[1-5]$/.test(选择)) return 活人.filter(单位 => 单位.位置 + 1 === Number(选择.at(-1)));
    switch (选择) {
    case 枚举.首领: {
        if (!来源为敌方) return [对方.find(单位 => 单位.编号 === 状态.当前受击来源 && 单位.生命 > 0) || 状态.敌人[状态.攻击目标]].filter(Boolean);
        // 解包Skill_C根因：威压反馈12903/12904与兰儿自身增益12899同为效果18，但记录类型分别是0x33"目标"作用域与0x07"自身"作用域；0x33与首领攻击26647、激情增伤26649/26650同作用域，在首领受击监听语境下取首领的攻击目标：嘲讽优先、无嘲讽回退攻击者（夏日实测叠在攻击者身上）。旧实现固定重定向到攻击者，对应逆向计算器whoActed的简化，不含嘲讽语义；SP实测第3回合威压被嘲讽者抢走、改操作顺序可叠回攻击者，均与此一致。
        const 嘲讽 = 状态.队伍.filter(单位 => 单位.生命 > 0 && 加成(单位, 枚举.嘲讽) > 0);
        const 攻击者 = 对方.find(单位 => 单位.编号 === 状态.当前受击来源 && 单位.生命 > 0) || 对方.find(单位 => 单位.生命 > 0);
        if (嘲讽.length) {
            // 多嘲讽时每个"首领"目标反馈效果各自独立均匀随机抽取一名存活嘲讽者：用户复核实测确认独立随机更正确；随机数走与概率判定同源的确定性LCG，单一嘲讽不消耗随机数，配合结算操作按动作注入的随机种子保证重放可复现，选人分布已由 BattleSys.GetRandomTarget(0x22a6c04) 汇编定案：RNG.Next(0,count)（vtable+0x198）均匀抽取、独立调用互不关联；作用域差别（0x33目标 vs 0x07自身）由 Skill_C 类型字段与 SetSkillTarget(0x229e7f4) 分派互证。
            const 选中 = 抽取随机目标(状态, 嘲讽, 枚举.首领受击反馈, { 技能: '矮人王的威压', 效果: 状态.当前反馈效果 || '反馈增益' });
            if (嘲讽.length > 1 || 选中 !== 攻击者) 记录(状态, 枚举.机制, `首领受击反馈：${嘲讽.length}人嘲讽候选，独立随机命中${选中.名称}`, null, 选中.位置);
            return [选中];
        }
        return [攻击者].filter(Boolean);
    }
    case 枚举.敌方全体: return 对方.filter(单位 => 单位.生命 > 0);
    case 枚举.自身: return [来源];
    case 枚举.其他: return 活人.filter(单位 => 单位.编号 !== 来源.编号);
    case 枚举.最低: return [最低生命目标(本方)].filter(Boolean);
    case 枚举.首位: return 活人.filter(单位 => 单位.位置 === 0);
    case 枚举.末位: return 活人.filter(单位 => 单位.位置 === 4);
    case 枚举.攻击妨碍: return 活人.filter(单位 => [枚举.攻击者, 枚举.妨碍者].includes(单位.职业));
    case 枚举.攻击治疗: return 活人.filter(单位 => [枚举.攻击者, 枚举.治疗者].includes(单位.职业));
    }
    const 职业 = { 攻击: 枚举.攻击者, 治疗: 枚举.治疗者, 辅助: 枚举.辅助者, 守护: 枚举.守护者 }[选择];
    if (职业) return 活人.filter(单位 => 单位.职业 === 职业);
    if ([枚举.火, 枚举.水, 枚举.风, 枚举.光, 枚举.暗].includes(选择)) return 活人.filter(单位 => 单位.属性 === 选择);
    if (选择 !== 枚举.全体) throw new Error(`尚未实现的效果目标：${选择}`);
    return 活人;
}

export function 加成(单位, 属性) {
    // 固定加攻在原执行器写入效果时就是整数，必须逐项取整后再求和，不能把多个小数效果先相加再取整。
    const 固定 = (单位.效果 || []).filter(效果 => 效果.属性 === 属性 && !来源被免疫(单位, 效果)).reduce((合计, 效果) => 合计 + (属性 === 枚举.攻击固定 ? Math.floor(效果.数值) : 效果.数值) * 效果.层数, 0);
    if (属性 === 枚举.攻击比例 && 单位.幸运物 >= 1) return 固定 + .30;
    if (属性 === 枚举.受疗增加 && 单位.幸运物 >= 2) return 固定 + .30;
    if (属性 === 枚举.普攻伤害 && 单位.幸运物 >= 3) return 固定 + .50;
    return 固定;
}

export function 当前攻击(单位) {
    const 数值 = 单位.攻击 * Math.max(0, 1 + 加成(单位, 枚举.攻击比例)) + 加成(单位, 枚举.攻击固定);
    return Math.max(0, Math.floor(数值 + Number.EPSILON * Math.max(1, Math.abs(数值)) * 4));
}

export function 当前护盾(单位) {
    return (单位.护盾 || []).filter(层 => !来源被免疫(单位, 层)).reduce((合计, 层) => 合计 + 层.数值, 0);
}

function 来源被免疫(目标, 效果) {
    return (目标.来源免疫 || []).some(项 => 项.剩余 > 0 && 项.技能 === 效果.来源技能 && (!项.属性 || 项.属性 === 效果.属性 || 项.属性 === 效果.异常));
}

function 添加增益(目标, 属性, 数值, 持续, 来源, 名称, 上限 = 1, 来源技能 = null, 加层数 = 1, 合并来源 = 来源.编号, 叠加 = false) {
    if (来源被免疫(目标, { 来源技能, 属性 })) return;
    if (!Number.isFinite(数值) || !Number.isInteger(持续) || 持续 < 0) throw new Error(`效果参数不合法：${名称}`);
    // 施加阶段取施加时的真实阶段：我方阶段施加的效果在敌方回合结束扣，敌方阶段施加的减益在我方回合结束扣（见扣减效果），时长以解包原值为准。
    const 敌方施加 = 当前状态?.阶段 === 枚举.敌方;
    const 已有 = 叠加 ? null : 目标.效果.find(效果 => 效果.名称 === 名称 && (效果.合并来源 ?? 效果.来源) === 合并来源 && 效果.属性 === 属性);
    if (已有) {
        已有.数值 = 数值;
        已有.剩余 = 持续;
        已有.层数 = Math.min(上限, 已有.层数 + 加层数);
    } else 目标.效果.push({ 属性, 数值, 剩余: 持续, 来源: 来源.编号, 合并来源, 名称, 层数: Math.min(上限, 加层数), 上限, 来源技能, ...(敌方施加 ? { 敌方施加: true } : {}) });
}

// 效果按施加阶段分流扣减点：我方阶段施加的效果在敌方回合结束扣（它刚经历了我方+敌方=完整回合），敌方阶段施加的减益在我方回合结束扣（它刚被敌方施加，须到下一个我方回合结束才算经历了一个回合）。这样解包原值时长N恰好覆盖N个完整回合，无需把+1补偿硬编码进时长，也不存在跳过扣减的豁免——那次扣减只是落在属于它的时点。递减随扣减点一起走。实测锚点：减疗5→枪匠T1/T2/T4各吃一层时T6三层俱在（剩1/2/4）、T7最老层到期；巧克力睡眠2→T5施加T6显示剩2；麻痹2→限制后恰好待机2回合；沉默3同口径；冷却暂停0在施加的敌方回合末按暂停冷却后、于下个我方回合末移除。
function 扣减效果(单位, 敌方施加) {
    单位.效果 = 单位.效果.filter(效果 => {
        if (Boolean(效果.敌方施加) !== 敌方施加) return true;
        return --效果.剩余 > 0;
    }).map(效果 => 效果.递减 && Boolean(效果.敌方施加) === 敌方施加 ? { ...效果, 数值: 效果.数值 - 效果.递减 } : 效果);
}

function 生命初始化增益(单位) {
    const 初始生命 = 单位.生命上限;
    const 增益基准 = 单位.生命增益基准 ?? 初始生命;
    const 增益 = (单位.效果 || []).filter(项 => 项.属性 === 枚举.生命比例 && !来源被免疫(单位, 项));
    // 原执行器的hpUpMe把每项生命增益独立向下取整后加到已经算出的初始生命，增益基准就是角色自身进场面板整数，与面板同源同值。
    单位.生命上限 = Math.max(1, 初始生命 + 增益.reduce((合计, 项) => 合计 + Math.floor(增益基准 * 项.数值 * 项.层数), 0));
    单位.生命 = 单位.生命上限;
}

