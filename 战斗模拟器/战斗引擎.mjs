function 随机数(状态) {
    状态.随机状态 = (Math.imul(状态.随机状态 ?? 20261113, 1664525) + 1013904223) >>> 0;
    return 状态.随机状态 / 4294967296;
}

function 抽取随机目标(状态, 候选, 来源, 说明 = null) {
    if (候选.length <= 1) return 候选[0] || null;
    状态.本操作有随机分支 = true;
    if (状态.配置.手动随机) {
        const 序号 = 状态.手动分支序 || 0;
        const 选择 = 状态.当前手动分支?.[序号];
        if (选择 === undefined) {
            const 错误 = new Error('请选择随机分支');
            错误.随机分支 = { 序号, 来源, 技能: 说明?.技能, 效果: 说明?.效果, 候选: 候选.map(单位 => ({ 编号: 单位.编号, 名称: 单位.名称, 位置: 单位.位置 })) };
            throw 错误;
        }
        const 选中 = 候选.find(单位 => 单位.编号 === 选择);
        if (!选中) throw new Error('保存的随机分支已失效，请重新选择');
        状态.手动分支序 = 序号 + 1;
        记录(状态, 枚举.机制, `${来源}：手动选择${选中.名称}`, null, 选中.位置);
        return 选中;
    }
    return 候选[Math.floor(随机数(状态) * 候选.length)];
}

function 判定概率(状态, 概率) {
    if (!Number.isFinite(概率) || 概率 < 0 || 概率 > 1) throw new Error('概率必须为 0 至 1');
    if (概率 === 1) return true;
    if (概率 === 0) return false;
    return 随机数(状态) < 概率;
}

