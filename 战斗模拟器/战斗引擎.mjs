function 派发原包触发(状态, 来源, 时机, 上下文 = {}) {
    if ((状态.原包触发深度 || 0) >= 12) throw new Error('原包触发链超过模型深度限制');
    状态.原包触发深度 = (状态.原包触发深度 || 0) + 1;
    try {
        const 时机列 = Array.isArray(时机) ? 时机 : [时机];
        // 追加方式先于触发方式执行：UseSkill(VA0x80022bfe1c) 在 DoAttack 主体后立即经 GetSpecialTriggerSkill(+0x3b4) 收集追加并以父类别递归 UseSkill(+0x59c, w0=父kind不变/w5=-1)，普通触发要到 DoAttackCallback 之后的 DoTriggerSkill(+0x6b0) 才执行；按注册顺序混排会让后注册的追加吃到先注册触发刚授予的增益（伊布力斯普攻追加28877误吃被动1触发14827的普攻伤害+30%即此因）。
        // 攻击者本次动作新注册的受击监听不得追溯触发本次攻击（与派发角色触发的注册批次排除同规则）：兰儿普攻注册的12901矮人王威压不反喂兰儿自己，由后续赛露西亚的攻击消耗（实测第2回合兰儿628252=floor(1329860.95×2.3×2.054×0.1)仅自身12899一层25%无造伤10%，赛503258=floor(973496.95×2.4×2.154×0.1)带反馈25%+10%；旧模拟兰儿自吃反馈叠两层25%得735767）。
        // 行动前快照：SetTriggerXXXSkill 在 SelectCharToXXX 内、UseSkill 执行前把当前监听快照入队，末尾 DoTriggerSkill 按队列派发——动作执行中新注册的监听不参与本次派发（与旧执行器 行动前有效 同构）。实测锚：枪匠T4普攻叠满3层穿甲弹时 58566条件授予的58567攻击时清弹监听本次不触发，弹保持3层→T5必杀吃435%攻+孤高+54.4%必杀伤（实测115665097×5=模拟无435%时33496861×3.4528），必杀自身攻击时才清弹（用户实测必杀后无弹）；旧实现行动末直查当前列表致叠满当次普攻即清、必杀前弹0。
        const 列 = 上下文.行动前快照 ? [...上下文.行动前快照].filter(项 => (来源.原包触发 || []).includes(项)) : [...(来源.原包触发 || [])];
        for (const 项 of 列.sort((甲, 乙) => Number(甲.方式 !== 枚举.追加) - Number(乙.方式 !== 枚举.追加))) {
            if (项.时机 === 枚举.被攻击 && 项.注册批次 != null && 项.注册批次 === 状态.当前伤害批次 && 项.原施法者 === 状态.当前受击来源) continue;
            if (项.条件授予 || 项.剩余 <= 0 || !时机列.includes(项.时机) || 项.时机 === 枚举.受到指定状态 && 项.状态ID !== 上下文.状态ID || 项.条件 && !原包条件成立(来源, 项.条件, 状态) || 项.周期 && (状态.回合 === 1 || (状态.回合 - 1) % 项.周期 !== 0)) continue;
            const 原施法者 = [...状态.队伍, ...状态.敌人].find(单位 => 单位.编号 === 项.原施法者) || 来源;
            const 次数 = 项.方式 === 枚举.按计数重复 ? 原包计数值(来源, 项.计数技能) : 1;
            for (let 次 = 0; 次 < 次数; 次++) for (const 子编号 of 项.子技能) 执行原包技能(状态, 来源, 子编号, { ...上下文, 原施法者, 接收阵营: 项.接收阵营 });
        }
    } finally { 状态.原包触发深度--; }
}

