function 我方承伤(状态, 目标, 数值, 真实 = false, 名称 = 枚举.敌方伤害, 触发受击 = true, 伤害来源 = null) {
    if (目标.生命 <= 0) return;
    const 属性倍率值 = 伤害来源 ? 属性倍率(伤害来源, 目标) : 1;
    const 属性易伤 = 伤害来源 ? 加成(目标, 易伤键(伤害来源.属性)) : 0;
    const 被克条件值 = 属性倍率值 > 1 ? Math.max(0, 1 + 加成(目标, '被克制减伤')) : 1;
    // 属性倍率参与同一前置伤害乘算后再向下取整；0.75改为先除4再乘3会破坏已实测的第2回合普攻与第4回合技能/普攻，不能用局部拟合替代统一结算。
    // 真伤与普伤均走 BattleCalculator 内核：真伤=基础×F6(仅防御区)，普伤 F8=受伤变化(受到伤害加成)、F3=属性倍率、F5=属性易伤×被克条件、F6=防御。
    let 伤害 = 计算伤害值({
        基础值: 数值, 倍率: 1,
        变化率: 0, 固定增减: 0,
        攻槽: { 属性: 伤害来源?.属性, 造成伤害: 0, 属性加成: 伤害来源 ? 加成(伤害来源, 枚举.相克抵消) : 0, 破防加成: 0 },
        守槽: {
            属性: 目标.属性, 受到伤害: 加成(目标, 枚举.受伤变化),
            属性加成: -加成(目标, 枚举.属性相克减少),
            属性受击加成: 伤害来源 ? { [伤害来源.属性]: Math.max(0, 1 + 属性易伤) * 被克条件值 - 1 } : {},
            防御作用中: Boolean(目标.防御), 防御减伤率: 防御基准减伤, 防御加成: 加成(目标, 枚举.防御减伤),
            破防作用中: false, 破防率: 0, 伤害变化率: 0,
        },
        类别: 1, 真实,
    });
    let 吸收 = 0;
    for (const 护盾 of 目标.护盾) {
        if (来源被免疫(目标, 护盾)) continue;
        const 本层吸收 = Math.min(护盾.数值, 伤害);
        护盾.数值 -= 本层吸收;
        伤害 -= 本层吸收;
        吸收 += 本层吸收;
    }
    目标.护盾 = 目标.护盾.filter(层 => 层.数值 > 0);
    const 有效 = Math.min(目标.生命, 伤害);
    目标.生命 -= 有效;
    if (有效 > 0 || 吸收 > 0) 解除睡眠(目标);
    // 日志记录完整伤害结算量；致死不能把数字截成剩余生命，方块K对站位4回退到万巴时两段仍应同为3062226。
    目标.统计.承伤 += 伤害;
    目标.统计.护盾吸收 += 吸收;
    状态.本回合.承伤 += 伤害;
    状态.本回合.护盾吸收 += 吸收;
    记录(状态, 枚举.承伤, `${目标.名称} · ${名称}${真实 ? ' · 真实' : ''}`, 伤害, 目标.位置);
    if (目标.生命 === 0) 记录(状态, 枚举.倒下, `${目标.名称}无法继续战斗`, null, 目标.位置);
    刷新条件增益(状态);
    if (触发受击) {
        const 原来源 = 状态.当前受击来源 ?? null;
        状态.当前受击来源 = 伤害来源?.编号 ?? null;
        try { 派发受击(状态, 目标, 名称 === 枚举.普攻 ? 枚举.普攻 : 枚举.必杀); }
        finally { 状态.当前受击来源 = 原来源; }
    }
}

function 结算持续伤害(状态, 目标列表) {
    for (const 目标 of 目标列表) {
        for (const 效果 of 目标.持续伤害 || []) {
            if (目标.生命 <= 0 || 效果.剩余 <= 0) continue;
            if (来源被免疫(目标, 效果)) { 效果.剩余--; continue; }
            const 来源 = 状态.队伍.find(单位 => 单位.编号 === 效果.来源);
            if (!来源) continue;
            if (状态.队伍.includes(目标)) 我方承伤(状态, 目标, 效果.基础 * Math.max(0, 1 + 加成(来源, 枚举.持续伤害增幅)) * Math.max(0, 1 + 加成(目标, 枚举.持续伤害易伤)), false, 效果.名称, false, 来源);
            else 造成伤害(状态, 来源, 1, 枚举.持续, 效果.名称, 目标, false, 效果.基础);
            效果.剩余--;
        }
        目标.持续伤害 = (目标.持续伤害 || []).filter(效果 => 效果.剩余 > 0);
    }
}

