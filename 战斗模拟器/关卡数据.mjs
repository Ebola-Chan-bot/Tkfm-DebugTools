export function 当前关卡(配置) {
    const 关卡 = 关卡列表.find(项 => 项.编号 === (配置.关卡 ?? '颠倒镜'));
    if (!关卡) throw new Error('未知关卡');
    return 关卡;
}

export function 敌方技能目录(配置, 位置 = 0) {
    return 当前关卡(配置).编号 === '夏日尾声' ? 夏日行动[夏日敌人[位置]?.编号] || [] : 首领技能;
}

