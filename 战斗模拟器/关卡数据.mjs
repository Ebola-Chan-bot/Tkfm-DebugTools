export function 计算原包敌方面板({ 基础生命, 基础攻击, 等级, 星等, 五星生命被动 = 0 }) {
    if (!Number.isInteger(等级) || 等级 < 1 || !Number.isInteger(星等) || 星等 < 0 || 星等 > 5 || ![基础生命, 基础攻击].every(值 => Number.isFinite(值) && 值 > 0) || !Number.isFinite(五星生命被动) || 五星生命被动 < 0) throw new Error('原包敌方属性或等级星等无效');
    const 成长 = 原包敌方资料.算法.每级倍率 ** (等级 - 1);
    const 星级倍率 = 1 + 原包敌方资料.算法.每星加成 * 星等;
    const 生命倍率 = 星等 >= 5 ? 1 + 五星生命被动 : 1;
    const 生命上限 = Math.floor(基础生命 * 成长 * 星级倍率 * 生命倍率);
    const 攻击 = Math.floor(基础攻击 * 成长 * 星级倍率);
    if (![生命上限, 攻击].every(值 => Number.isSafeInteger(值) && 值 > 0)) throw new Error('原包敌方面板超出有效数值范围');
    return { 生命上限, 攻击 };
}

