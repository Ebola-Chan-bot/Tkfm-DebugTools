// 敌方等级星级公式：每级倍率与每星加成均由 Character_C 面板反推实证（基础×(1+0.2×星3)×1.1^(级-1)=初始面板：2173×1.6×1.1^68 等三例逐位一致，公式形状与系数为数据实证，非外部源引用）。
const 每星加成 = 0.2;
// 关卡基础参数=Stage_C/MonsterGroup 原包直读：Stage_C 60B 行 u16@17=编组编号、u8@19=等级、u8@20=星等；MonsterGroup 22B 行=编组编号+敌人编号双槽序列。三关卡（15249/60155/60161）与旧常量逐字段对照一致。
const 关卡基础 = 关卡编号 => {
    const 关 = 原包关卡表.get(关卡编号);
    if (!关) throw new Error('原包缺少关卡：' + 关卡编号);
    return { 关卡编号, 等级: 关.等级, 星等: 关.星等, 敌人编号: 原包编组表.get(关.编组编号) ?? [] };
};
// 五星生命被动=技能组被动3（槽9）的 SkillStr 原包文本"最大HP增加X%"提取（与旧常量 0.8/0.5/1 逐一对齐；被动前后分别向下取整见 计算原包敌方面板）。
const 五星生命被动 = 编号 => {
    const 说明 = 原包文本.get(原包机制.技能组[编号 * 10 + 1]?.[9])?.[1] ?? '';
    const 数值 = 说明.match(/(?:^|\n)最大HP增加([\d.]+)%/);
    return 数值 ? Number(数值[1]) / 100 : 0;
};

export function 计算原包敌方面板({ 基础生命, 基础攻击, 等级, 星等, 五星生命被动 = 0 }) {
    if (!Number.isInteger(等级) || 等级 < 1 || !Number.isInteger(星等) || 星等 < 0 || 星等 > 5 || ![基础生命, 基础攻击].every(值 => Number.isFinite(值) && 值 > 0) || !Number.isFinite(五星生命被动) || 五星生命被动 < 0) throw new Error('原包敌方属性或等级星等无效');
    const 成长 = 每级倍率 ** (等级 - 1);
    const 星级倍率 = 1 + 每星加成 * 星等;
    const 生命倍率 = 星等 >= 5 ? 1 + 五星生命被动 : 1;
    const 生命上限 = Math.floor(Math.floor(基础生命 * 成长 * 星级倍率) * 生命倍率);
    const 攻击 = Math.floor(基础攻击 * 成长 * 星级倍率);
    if (![生命上限, 攻击].every(值 => Number.isSafeInteger(值) && 值 > 0)) throw new Error('原包敌方面板超出有效数值范围');
    return { 生命上限, 攻击 };
}

// 敌方身份推导（CharacterStr_sc/Character_C）：名称=全名末段、全名=文本1（全角空格归一）、属性=Character_C u8@8。敌人名称不入战斗记录（记录存编号），显示时按编号反查。
export const 敌方名称 = 编号 => 原包角色文本.get(编号)?.名称 ?? `编号${编号}`;
export const 敌方全名 = 编号 => 原包角色文本.get(编号)?.全名 ?? `编号${编号}`;
export const 敌方属性 = 编号 => 原包角色表.get(编号)?.属性 ?? 枚举.无;

// 敌方编组：关卡编号→该关卡全部敌人（Stage_C→MonsterGroup→逐敌组装）。名称/属性=原包反查；面板=基础×等级成长×星级倍率。
// 面板证据链：爱你至死不渝（Stage_C 等级71、星等5）生命=Character_C 基础HP+技能26585 最大HP+100%、被动前后分别取整；攻击=Character_C 基础ATK500×1.1^70×星级2 向下取整得789746（属性编码2=水，水打风0.75；攻击技能单段结算总倍率乘完取整，首回合普攻592309 已实测归因）。夏日尾声（等级68、星等4，四星不启用被动3）五敌实测逐整数一致。颠倒镜（等级70、星等5）技能22810 最大HP+80%、攻击=基础ATK682×1.1^69×星级2 向下取整。
export function 敌方编组(关卡编号) {
    return 关卡基础(关卡编号).敌人编号.map(编号 => {
        const 资料 = 原包角色表.get(编号);
        if (!资料) throw new Error('原包缺少敌方角色记录：' + 编号);
        if (资料.属性 === 枚举.无) throw new Error(`原包敌人属性编码无效：${编号}`);
        const 五星被动 = 五星生命被动(编号);
        return {
            编号, 名称: 敌方名称(编号), 全名: 敌方全名(编号), 属性: 资料.属性,
            基础生命: 资料.基础生命, 基础攻击: 资料.基础攻击, 五星生命被动: 五星被动,
            ...计算原包敌方面板({ 基础生命: 资料.基础生命, 基础攻击: 资料.基础攻击, 五星生命被动: 五星被动, ...关卡基础(关卡编号) }),
        };
    });
}

// 关卡标签=简称前缀推导（'塔'→魔狱塔、'时'→时之裂缝，数字后缀→第 N 层/季）。'时之裂缝'一词见于 EventStr 季描述（时之裂缝-第N季）而 StageStr 只有'时-SP'类简称，故模式名按简称前缀（'塔-55'/'时-SP'）区分。
const 标签推导 = 简称 => {
    const 匹配 = String(简称 || '').match(/^(塔|时)-(\w+)$/);
    if (!匹配) return String(简称 || '');
    const 模式 = 匹配[1] === '塔' ? '魔狱塔' : '时之裂缝';
    return /^\d+$/.test(匹配[2]) ? `${模式} · 第 ${匹配[2]} ${匹配[1] === '塔' ? '层' : '季'}` : 模式;
};

// 关卡列表：名称/简称=StageStr 原包文本；头像=敌方一号位→Character_C 登场角色→cs{登场}_0_0.webp；头像角色=敌方一号位全名。
export const 关卡列表 = 关卡编号组.map(编号 => {
    const 文 = 原包关卡文本.get(编号) ?? {};
    const 敌 = 敌方编组(编号);
    const 首领 = 敌[0];
    const 登场 = 原包角色表.get(首领.编号)?.登场角色;
    // 多队场次=MultiteamStage_C 原包直读（活动9027多队15209=[15234,15239,15244,15249]，15249=第4场/共4场）；不在多队表的关卡（魔狱塔等）无场次标注。
    const 多队 = 原包多队表.get(编号) ?? null;
    return {
        编号, 名称: 文.名称 ?? `关卡${编号}`, 简称: 文.简称 ?? '', 标签: 标签推导(文.简称),
        多队, 场次标注: 多队 ? `第 ${多队.场次} 场 / 共 ${多队.总场次} 场` : '',
        头像: 登场 ? `./角色头像/cs${登场}_0_0.webp` : '', 头像角色: 首领.全名,
    };
});

export function 当前关卡(配置) {
    const 关卡 = 关卡列表.find(项 => 项.编号 === (配置.关卡));
    if (!关卡) throw new Error('未知关卡');
    return 关卡;
}

// 敌方技能目录：EnemyAI 规则行技能（动作码9=阶段切换→递归目标组）+SkillGroup 槽6普攻；名称/说明=SkillStr 原包原文。旧 关卡行动/首领技能 常量表按此推导替代（同场同名不同编号的行动以技能编号唯一标识，名称仅显示）。
export function 敌方技能目录(敌人编号) {
    const 树 = (编号, 已见 = new Set()) => {
        if (已见.has(编号)) return [];
        已见.add(编号);
        return (敌方规则[编号] || []).flatMap(规则 => 规则.动作码 === 9 ? 树(规则.技能编号, 已见) : (规则.技能编号 ? [规则.技能编号] : []));
    };
    const 槽 = 原包机制.技能组[敌人编号 * 10 + 1] || [];
    const 编号列 = [...new Set([槽[5], ...树(敌人编号)].filter(Boolean))];
    return 编号列.map(编号 => {
        const 文 = 原包文本.get(编号);
        return [文?.[0] || `技能${编号}`, 编号, 文?.[1] || ''];
    });
}

// 敌方技能名称：SkillStr 原包文本反查（战斗记录/日志存技能编号，显示时按编号取名；同场同名不同编号不去重、不加区分后缀）。
export function 敌方技能名称(编号) {
    if (!编号) return '普攻';
    return 原包文本.get(编号)?.[0] || `技能${编号}`;
}

export function 创建关卡配置(关卡, 队伍) {
    if (!关卡列表.some(项 => 项.编号 === 关卡)) throw new Error('未知关卡');
    // 只给关卡事实（原包直读的首领身份与计算面板）；一切可调数值（减伤/受疗受盾/回合上限/敌方星等/AI 冷却与事件时点）不设默认，由设置表单显式输入。敌人存编号+可编辑面板（不存名称/属性，显示时按编号反查）。
    const 敌 = 敌方编组(关卡);
    const 配置 = { 关卡, 队伍: 队伍 ? structuredClone(队伍) : [], 首领编号: 敌[0].编号, 首领生命: 敌[0].生命上限, 首领攻击: 敌[0].攻击 };
    if (敌.length > 1) 配置.敌人 = 敌.map(({ 编号, 生命上限, 攻击 }) => ({ 编号, 生命上限, 攻击 }));
    return 配置;
}
