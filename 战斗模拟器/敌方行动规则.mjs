export function 求值敌方条件(条件, 上下文) {
    const { 编号, 参数一, 参数二 } = 条件;
    const { 状态, 单位 } = 上下文;
    switch (编号) {
        case 0: case 1: case 2: return true;
        case 23: return 单位.生命 * 100 < 单位.生命上限 * 参数一;
        case 80: return 单位.生命 * 100 <= 单位.生命上限 * 参数一;
        case 31: return 状态.回合 === 参数一;
        // 汇编锚：AI.checkCondition(0x2198320) 跳转表 entry33（条件码34）→case块0x2198820 取 BattleSys.get_RoundCount(0x229a0a8)，跳公共尾段0x21988f0 做 sdiv/msub 求 回合%参数一，余数非0即假（cbnz→0x2199900 返回0），余0则落 0x2198a10 走 get_TurnUseSkill 位检查（每回合一次门，与条件2共用尾段）；参数二不参与取模，故 34=纯周期整除（回合为参数一整数倍），区别于 38 的 (回合-参数二)%参数一 偏移周期。每回合一次的重复触发由引擎 触发模式/已执行 机制承载，此处只判周期。
        case 34: return 参数一 > 0 && 状态.回合 % 参数一 === 0;
        // 汇编锚：checkCondition 跳转表 entry35（条件36）→case块0x21988a4 先 get_RoundCount cmp 参数一 b.lt假（回合>=参数一），再 (回合-参数二) sdiv/msub 参数一 余0真，落0x2198a10 get_TurnUseSkill 每回合一次门。与38同为偏移周期但下限独立取参数一（38下限=参数二>0?参数二:参数一），故36=(回合>=参数一)&&(回合-参数二)%参数一==0。SP2阶段组55051槽15(36参4,2)→回合6/10/14切回43232，与槽6(34参4)回合4/8/12切入55051交替。
        case 36: return 参数一 > 0 && 状态.回合 >= 参数一 && (状态.回合 - 参数二) % 参数一 === 0;
        case 38: {
            if (!(参数一 > 0)) return false;
            const 起始回合 = 参数二 > 0 ? 参数二 : 参数一;
            return 状态.回合 >= 起始回合 && (状态.回合 - 起始回合) % 参数一 === 0;
        }
        // 汇编锚：checkCondition 跳转表 entry74（条件75）→case块0x2198fe8 取 get_HasUseSkill 位字段经 ValueUtil.GetValueBitCount0_n@0x2611a9c（(值>>参数一)&1）cmp#1 判位[参数一]==1，真则 bitset@0x2611f08(val0) 清该位并 set_HasUseSkill 回写（消费）后返回真。位索引=槽位（chkIsCanUseSkill 以行索引查位）。模拟器以 AI状态.已用位 按槽位置位承载（执行AI技能），此处判位[参数一]已置（=对应槽位技能已执行，如55051槽0-2名牌包包/香水/大衣→槽12-14 cond75参0/1/2选包包乱打/香水乱喷/大衣乱甩）。游戏真值会清位消费使名牌可再触发轮换，引擎现有 已执行 整场门控下每阶段入口各乱打触发一次，消费轮换待SP2独立实测锚点再精化（与SP3同属未实测关卡）。
        case 75: return ((单位.AI状态?.已用位 || 0) >>> 参数一 & 1) === 1;
        case 56: return 状态.队伍.filter(项 => 项.生命 > 0).length <= 参数一;
        case 57: return 状态.敌人.filter(项 => 项.生命 > 0).length === 参数一;
        case 60: case 61: case 62: return (状态.我方动作计数?.[[枚举.普攻, 枚举.必杀, 枚举.防御][编号 - 60]] || 0) >= 参数一;
        case 98: case 100: {
            // 汇编锚：AI.checkCondition(0x2198320) 跳转表 98→ChkCharsSkillState(比较=至少)/100→(比较=等值)；ChkCharsSkillState(0x229c9b8) 遍历玩家队伍 TSkillStateData 匹配 skillId==参数一，有效层数=mergeTimes、<1 时回退 duration（与 GetSkillIdMergeTimes 0x218e29c 的 -1 哨兵回退同构）。原包标记/计数/增益共用 TSkillStateData 载体（metadata 字段 skillId/mergeTimes/duration），模拟器分立 计数/状态标记/效果 三载体，此处按授予技能编号统一读取；旧实现只查状态标记致计数型引用（爱你 26607 过从甚密）条件永假。
            const 引用 = 原包机制.技能[参数一]?.效果;
            const 计数键 = 引用?.类型 === 枚举.计数 ? (引用.键 ?? 参数一) : null;
            return 状态.队伍.some(角色 => {
                const 层数 = 计数键 !== null ? (角色.计数?.[计数键] || 0) : Math.max(0,
                    ...(角色.状态标记 || []).filter(项 => 项.来源技能 === 参数一 && 项.剩余 > 0).map(项 => 项.层数 >= 1 ? 项.层数 : 项.剩余),
                    ...(角色.效果 || []).filter(项 => 项.来源技能 === 参数一 && 项.剩余 > 0).map(项 => 项.层数 >= 1 ? 项.层数 : 项.剩余));
                return 编号 === 98 ? 层数 >= 参数二 : 层数 === 参数二;
            });
        }
        case 74: return 上下文.时点 === 枚举.开场;
        default: {
            // CD 类条件（13/16/42/45/76/78）的字段与比较方式由 默认CD条件 跳转表给出（可被 配置.AICD条件 逐码覆盖），与上方固定条件码互不相交，故在 default 查表。
            if (默认CD条件[编号]) return 比较冷却(状态.配置?.AICD条件?.[编号] || 默认CD条件[编号], 单位, 参数一);
            throw new Error(`尚未实现 AI 条件 ${编号}（${参数一}，${参数二}）`);
        }
    }
}

export function 匹配敌方规则(规则, 上下文) {
    const 条件 = 规则.条件.filter(项 => 项.编号 !== 0);
    if (!条件.length) return true;
    const 结果 = 条件.map(项 => 求值敌方条件(项, 上下文));
    return 规则.条件连接 === 1 ? 结果.every(Boolean) : 结果.some(Boolean);
}
