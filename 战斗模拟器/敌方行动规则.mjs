export function 求值敌方条件(条件, 上下文) {
    const { 编号, 参数一, 参数二 } = 条件;
    const { 状态, 单位 } = 上下文;
    if (编号 === 0 || 编号 === 1 || 编号 === 2) return true;
    if (默认CD条件[编号]) return 比较冷却(状态.配置?.AICD条件?.[编号] || 默认CD条件[编号], 单位, 参数一);
    if (编号 === 23) return 单位.生命 * 100 < 单位.生命上限 * 参数一;
    if (编号 === 80) return 单位.生命 * 100 <= 单位.生命上限 * 参数一;
    if (编号 === 31) return 状态.回合 === 参数一;
    if (编号 === 38) return 参数一 > 0 && 状态.回合 % 参数一 === 参数二 % 参数一;
    if (编号 === 56) return 状态.队伍.filter(项 => 项.生命 > 0).length <= 参数一;
    if (编号 === 57) return 状态.敌人.filter(项 => 项.生命 > 0).length === 参数一;
    if ([60, 61, 62].includes(编号)) return (状态.我方动作计数?.[['普攻', '必杀', '防御'][编号 - 60]] || 0) >= 参数一;
    if (编号 === 74) return 上下文.时点 === '开场';
    throw new Error(`尚未实现 AI 条件 ${编号}（${参数一}，${参数二}）`);
}

export function 匹配敌方规则(规则, 上下文) {
    const 条件 = 规则.条件.filter(项 => 项.编号 !== 0);
    if (!条件.length) return true;
    const 结果 = 条件.map(项 => 求值敌方条件(项, 上下文));
    return 规则.条件连接 === 1 ? 结果.every(Boolean) : 结果.some(Boolean);
}