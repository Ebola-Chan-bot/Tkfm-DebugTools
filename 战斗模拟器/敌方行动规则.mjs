const AI字节 = await 读取原包文件('EnemyAI.bytes');
// 字节读取用 Uint8Array 兼容写法（浏览器 fetch 与 Node fs 双通道均为 Uint8Array/Buffer，Buffer 专属 API 不可用）。
const 读u16 = 偏 => AI字节[偏] | (AI字节[偏 + 1] << 8);
const 读u32 = 偏 => (AI字节[偏] | (AI字节[偏 + 1] << 8) | (AI字节[偏 + 2] << 16) | (AI字节[偏 + 3] << 24)) >>> 0;
const 读i32 = 偏 => (AI字节[偏] | (AI字节[偏 + 1] << 8) | (AI字节[偏 + 2] << 16) | (AI字节[偏 + 3] << 24)) | 0;
const 读i8 = 偏 => (AI字节[偏] << 24) >> 24;
const 组数 = 读u32(0);

const 原始规则 = {};
for (let 组序 = 0; 组序 < 组数; 组序++) {
    const 组头 = 4 + 组序 * 703;
    const 编号 = 读u16(组头);
    const 行列 = [];
    for (let 槽位 = 0; 槽位 < 20; 槽位++) {
        const o = 组头 + 3 + 槽位 * 35;
        const 条件 = 偏 => ({ 编号: AI字节[o + 偏], 参数一: 读i32(o + 偏 + 2), 参数二: 读i32(o + 偏 + 6) });
        const 行 = {
            动作码: 读u16(o), 技能编号: 读u32(o + 2), 附加编号: 读u16(o + 6),
            行为标志: 读u16(o + 8), 触发模式: 读u16(o + 10),
            条件: [条件(12), 条件(22)], 条件连接: AI字节[o + 32], 目标码: AI字节[o + 33], 选敌码: 读i8(o + 34),
        };
        if (!行.动作码 && !行.技能编号 && !行.目标码 && !行.选敌码) break;
        行列.push({ 槽位, ...行 });
    }
    if (行列.length) 原始规则[编号] = 行列;
}
