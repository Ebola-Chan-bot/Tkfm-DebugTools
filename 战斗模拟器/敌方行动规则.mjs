export function 校验AI配置(配置) {
    for (const [编号, 条件] of Object.entries(配置.AICD条件 || {})) {
        if (!默认CD条件[编号] || !['最大冷却', '当前冷却'].includes(条件.字段) || !比较方式.includes(条件.比较)) throw new Error(`无效的 AI 条件校准：${编号}`);
    }
    if (!Number.isInteger(配置.敌方星等 ?? 4) || (配置.敌方星等 ?? 4) < 1 || (配置.敌方星等 ?? 4) > 5) throw new Error('敌方星等须为 1 至 5');
    if (!['伤害后', '行动后'].includes(配置.AI事件时点 ?? '伤害后')) throw new Error('无效的 AI 事件时点');
}

function 比较冷却(条件, 单位, 参数) {
    const 数值 = 单位.AI状态?.[条件.字段] ?? 0;
    if (条件.比较 === '==') return 数值 === 参数;
    if (条件.比较 === '!=') return 数值 !== 参数;
    if (条件.比较 === '>') return 数值 > 参数;
    if (条件.比较 === '>=') return 数值 >= 参数;
    if (条件.比较 === '<') return 数值 < 参数;
    return 数值 <= 参数;
}

